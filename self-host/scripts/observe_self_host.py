#!/usr/bin/env python3
"""Canonical ggen self-host observer.

Pipeline:
  raw repository census
  -> Git-object byte semantics
  -> file-header generation authority
  -> live authority and load-path normalization
  -> active root-output authority
  -> Gall program/checkpoint/work-item projection
  -> deterministic RDF/JSON/receipt outputs
"""
from __future__ import annotations

import argparse
import importlib.util
import json
import re
from collections import Counter
from pathlib import Path, PurePosixPath
from types import ModuleType
from typing import Any


GENERATED_HEADER = re.compile(
    r"^\s*(?:(?://[/!]?)|#|<!--|/\*+|\*)?\s*(?:"
    r"GENERATED by|GENERATED:|AUTO-?GENERATED|DO NOT EDIT|Do not edit by hand|@generated|"
    r"Generated\b.*\bDO NOT EDIT"
    r")(?:\b|\s|-->|$)",
    re.IGNORECASE,
)


def load(name: str, path: Path) -> ModuleType:
    spec = importlib.util.spec_from_file_location(name, path)
    if spec is None or spec.loader is None:
        raise RuntimeError(f"cannot load {name} from {path}")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


SCRIPTS = Path(__file__).resolve().parent
EXACT = load("ggen_self_exact_tree", SCRIPTS / "observe_exact_tree.py")
NORMALIZER = load("ggen_self_normalizer", SCRIPTS / "normalize_observation.py")
MODEL = EXACT.MODEL
write_outputs = EXACT.write_outputs


def has_generated_header(root: Path, path: str) -> bool:
    """Recognize a file-level generated claim, never an arbitrary body mention."""
    header = MODEL.read_bytes(root, path)[:4096].decode("utf-8", errors="replace")
    return any(GENERATED_HEADER.match(line) for line in header.splitlines()[:24])


def canonical_authority(file: dict[str, Any]) -> str:
    """Classify by provenance before location: generated law is not authored law."""
    path = str(file["path"])
    p = PurePosixPath(path)
    parts = set(p.parts)
    suffix = p.suffix.lower()
    if parts & NORMALIZER.ARCHIVE_SEGMENTS or any(part.startswith("archive_") for part in p.parts):
        return "Archive"
    if path.startswith("evidence/") or "/receipts/" in path or path.endswith("receipt.json"):
        return "VerificationEvidence"
    if suffix in NORMALIZER.TEMPLATE_EXTENSIONS:
        return "Template"
    if "/tests/" in path or "/fixtures/" in path or path.startswith("tests/"):
        return "TestFixture"
    if file["generated_marker"]:
        return "GeneratedConsequence"
    if (
        path in {"Cargo.toml", "ggen.toml", "rust-toolchain.toml", "CONSTITUTION.md"}
        or path.startswith(".specify/") and suffix in {".ttl", ".rq"}
        or re.match(r"^packs/[^/]+/(ontology\.ttl|pack\.toml|gates/.*\.rq)$", path)
        or path == "self-host/ontology.ttl"
    ):
        return "AuthoredConstitution"
    if path.startswith(NORMALIZER.BOOTSTRAP_PREFIXES):
        return "BootstrapKernel"
    if path.startswith(".github/workflows/") and suffix in {".yml", ".yaml"}:
        return "Workflow"
    if suffix in NORMALIZER.SOURCE_EXTENSIONS:
        return "ExecutableSource"
    if suffix == ".md" or path.startswith("docs/") or path.startswith("book/"):
        return "Documentation"
    if suffix in NORMALIZER.CONFIG_EXTENSIONS or p.name in {"justfile", "Makefile", "Makefile.toml"}:
        return "Configuration"
    return "Asset"


def canonical_load_bearing(path: str, authority: str) -> bool:
    if authority in {"Archive", "Template", "TestFixture", "VerificationEvidence", "Documentation", "Asset"}:
        return False
    if authority in {"AuthoredConstitution", "BootstrapKernel", "Workflow"}:
        return True
    if path in {"Cargo.toml", "ggen.toml", "justfile"}:
        return True
    return path.startswith(("crates/", "packs/", "scripts/", ".github/actions/", ".github/workflows/"))


def finalize_active_outputs(observation: dict[str, Any]) -> dict[str, Any]:
    """Treat every root manifest output as a generated consequence by contract."""
    owned = {
        claim["output_path"]
        for claim in observation["output_claims"]
        if claim["claim_kind"] == "active-manifest-rule" and claim["consumer"] == "."
    }
    for file in observation["files"]:
        if file["path"] in owned:
            file["authority_class"] = "GeneratedConsequence"
            file["load_bearing"] = True
    counts = Counter(file["authority_class"] for file in observation["files"])
    observation["authority_counts"] = dict(sorted(counts.items()))
    observation["counts"]["generated"] = counts.get("GeneratedConsequence", 0)
    observation["counts"]["unknown_authority"] = counts.get("UnknownAuthority", 0)
    observation.pop("observation_digest", None)
    canonical = json.dumps(observation, sort_keys=True, separators=(",", ":")).encode("utf-8")
    observation["observation_digest"] = MODEL.sha256(canonical)
    return observation


def observe(root: Path) -> dict[str, object]:
    observation = EXACT.observe(root)
    for file in observation["files"]:
        file["generated_marker"] = has_generated_header(root, str(file["path"]))
    NORMALIZER.authority_for = canonical_authority
    NORMALIZER.load_bearing = canonical_load_bearing
    return finalize_active_outputs(NORMALIZER.normalize(observation, MODEL))


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, help="repository root")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    root = (args.root or Path(__file__).resolve().parents[2]).resolve()
    return write_outputs(root, observe(root), args.check)


if __name__ == "__main__":
    raise SystemExit(main())
