#!/usr/bin/env python3
"""Canonical ggen self-host observer.

Pipeline:
  raw repository census
  -> Git-object byte semantics
  -> file-header generation authority
  -> live authority and load-path normalization
  -> constitutional placeholder refusal
  -> experimental/research namespace fences
  -> independently verified standalone products
  -> active root-output authority
  -> Gall program/checkpoint/work-item projection
  -> deterministic RDF/JSON/receipt outputs
"""
from __future__ import annotations

import argparse
import importlib.util
import json
import re
from collections import Counter
from pathlib import Path, PurePosixPath
from types import ModuleType
from typing import Any


GENERATED_HEADER = re.compile(
    r"^\s*(?:(?://[/!]?)|#|<!--|/\*+|\*)?\s*(?:"
    r"GENERATED by|GENERATED:|AUTO-?GENERATED|DO NOT EDIT|Do not edit by hand|@generated|"
    r"Generated\b.*\bDO NOT EDIT"
    r")(?:\b|\s|-->|$)",
    re.IGNORECASE,
)
CONSTITUTIONAL_SENTINELS = (
    "OWNER/REPOSITORY",
    "1979-01-01T00:00:00Z",
)


def load(name: str, path: Path) -> ModuleType:
    spec = importlib.util.spec_from_file_location(name, path)
    if spec is None or spec.loader is None:
        raise RuntimeError(f"cannot load {name} from {path}")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


SCRIPTS = Path(__file__).resolve().parent
EXACT = load("ggen_self_exact_tree", SCRIPTS / "observe_exact_tree.py")
NORMALIZER = load("ggen_self_normalizer", SCRIPTS / "normalize_observation.py")
MODEL = EXACT.MODEL
write_outputs = EXACT.write_outputs


def has_generated_header(root: Path, path: str) -> bool:
    """Recognize a file-level generated claim, never an arbitrary body mention."""
    header = MODEL.read_bytes(root, path)[:4096].decode("utf-8", errors="replace")
    return any(GENERATED_HEADER.match(line) for line in header.splitlines()[:24])


def canonical_authority(file: dict[str, Any]) -> str:
    """Classify by provenance before location: generated law is not authored law."""
    path = str(file["path"])
    p = PurePosixPath(path)
    parts = set(p.parts)
    suffix = p.suffix.lower()
    if parts & NORMALIZER.ARCHIVE_SEGMENTS or any(part.startswith("archive_") for part in p.parts):
        return "Archive"
    if path.startswith("evidence/") or "/receipts/" in path or path.endswith("receipt.json"):
        return "VerificationEvidence"
    if suffix in NORMALIZER.TEMPLATE_EXTENSIONS:
        return "Template"
    if "/tests/" in path or "/fixtures/" in path or path.startswith("tests/"):
        return "TestFixture"
    if file["generated_marker"]:
        return "GeneratedConsequence"
    if (
        path in {"Cargo.toml", "ggen.toml", "rust-toolchain.toml", "CONSTITUTION.md"}
        or path.startswith(".specify/") and suffix in {".ttl", ".rq"}
        or re.match(r"^packs/[^/]+/(ontology\.ttl|pack\.toml|gates/.*\.rq)$", path)
        or path == "self-host/ontology.ttl"
    ):
        return "AuthoredConstitution"
    if path.startswith(NORMALIZER.BOOTSTRAP_PREFIXES):
        return "BootstrapKernel"
    if path.startswith(".github/workflows/") and suffix in {".yml", ".yaml"}:
        return "Workflow"
    if suffix in NORMALIZER.SOURCE_EXTENSIONS:
        return "ExecutableSource"
    if suffix == ".md" or path.startswith("docs/") or path.startswith("book/"):
        return "Documentation"
    if suffix in NORMALIZER.CONFIG_EXTENSIONS or p.name in {"justfile", "Makefile", "Makefile.toml"}:
        return "Configuration"
    return "Asset"


def canonical_load_bearing(path: str, authority: str) -> bool:
    if authority in {"Archive", "Template", "TestFixture", "VerificationEvidence", "Documentation", "Asset"}:
        return False
    if authority in {"AuthoredConstitution", "BootstrapKernel", "Workflow"}:
        return True
    if path in {"Cargo.toml", "ggen.toml", "justfile"}:
        return True
    return path.startswith(("crates/", "packs/", "scripts/", ".github/actions/", ".github/workflows/"))


def detect_constitutional_placeholders(root: Path, observation: dict[str, Any]) -> dict[str, Any]:
    """Refuse sample identities and dates embedded in live constitutional law."""
    additions: list[dict[str, Any]] = []
    for file in observation["files"]:
        if file["authority_class"] != "AuthoredConstitution" or not file["load_bearing"]:
            continue
        path = str(file["path"])
        text = MODEL.read_bytes(root, path).decode("utf-8", errors="replace")
        present = [sentinel for sentinel in CONSTITUTIONAL_SENTINELS if sentinel in text]
        if not present:
            continue
        additions.append(
            MODEL.finding(
                "constitutional-placeholder",
                "High",
                f"Constitutional surface `{path}` embeds sample observation values: {', '.join(present)}.",
                path,
                "Move sample individuals into a named fixture and project exact repository observations into the consumer graph at execution time.",
                "A schema may be reusable, but sample repository identities and timestamps cannot establish standing for the live repository.",
                "Do not replace the sentinel with a newly hand-copied owner, repository, date, count, or workflow list.",
                "The constitutional file contains only reusable vocabulary and policy; exact repository individuals are emitted by the observer and independently verified.",
                "python3 self-host/scripts/observe_self_host.py --check",
            )
        )
    observation["findings"] = sorted(
        {item["finding_id"]: item for item in observation["findings"] + additions}.values(),
        key=lambda item: (item["severity_order"], item["category"], item["finding_id"]),
    )
    observation["counts"]["findings"] = len(observation["findings"])
    observation["counts"]["blocking_findings"] = sum(
        item["severity"] == "Blocking" for item in observation["findings"]
    )
    return observation


def preserve_research_fences(root: Path, observation: dict[str, Any]) -> dict[str, Any]:
    """Do not manufacture fake pack contracts for explicitly dormant research artifacts."""
    retained: list[dict[str, Any]] = []
    replacements: list[dict[str, Any]] = []
    for finding in observation["findings"]:
        if finding["category"] != "pack-contract":
            retained.append(finding)
            continue
        directory = str(finding["evidence_path"]).rstrip("/")
        readme = root / directory / "README.md"
        text = readme.read_text(encoding="utf-8", errors="replace") if readme.is_file() else ""
        lowered = text.lower()
        if not ("experimental" in lowered and "not wired" in lowered and "research artifact" in lowered):
            retained.append(finding)
            continue
        replacements.append(
            MODEL.finding(
                "pack-namespace",
                "Medium",
                f"Research artifact `{directory}` occupies the production pack namespace without production standing.",
                directory,
                "Move the artifact under a governed research namespace, or admit it as a real pack only after an automatic Rust-to-RDF extractor, consumer evidence, and CI exist.",
                "The artifact deliberately has no pack.toml or production load path; adding those files now would convert an honest boundary into a false capability claim.",
                "Do not add a placeholder pack.toml, synthetic extractor receipt, or green CI that validates only hand-transcribed fixtures.",
                "The artifact is either isolated under a research boundary with its limitations preserved, or promoted through a real extractor, pack contract, consumer, falsifier, and replay receipt.",
                "python3 self-host/scripts/observe_self_host.py --check",
            )
        )
    observation["findings"] = sorted(
        {item["finding_id"]: item for item in retained + replacements}.values(),
        key=lambda item: (item["severity_order"], item["category"], item["finding_id"]),
    )
    observation["counts"]["findings"] = len(observation["findings"])
    observation["counts"]["blocking_findings"] = sum(
        item["severity"] == "Blocking" for item in observation["findings"]
    )
    return observation


def admit_standalone_products(root: Path, observation: dict[str, Any]) -> dict[str, Any]:
    """Convert independently verified non-workspace crates into explicit load paths."""
    workflow_paths = [
        str(file["path"])
        for file in observation["files"]
        if str(file["path"]).startswith(".github/workflows/")
    ]
    workflow_text = {
        path: MODEL.read_bytes(root, path).decode("utf-8", errors="replace")
        for path in workflow_paths
    }
    verified: dict[str, str] = {}
    for package in observation["cargo_packages"]:
        path = str(package["path"])
        parts = PurePosixPath(path).parts
        if len(parts) != 2 or parts[0] != "crates" or path in observation["workspace_members"]:
            continue
        manifest = f"{path}/Cargo.toml"
        for workflow, text in workflow_text.items():
            if manifest in text or f"working-directory: {path}" in text or f"cd {path}" in text:
                verified[path] = workflow
                break
    if not verified:
        return observation
    observation["findings"] = [
        finding
        for finding in observation["findings"]
        if not (
            finding["category"] == "workspace-closure"
            and any(finding["evidence_path"] == f"{path}/Cargo.toml" for path in verified)
        )
    ]
    known_ids = {item["id"] for item in observation["load_paths"]}
    for path, workflow in sorted(verified.items()):
        identity = f"standalone-{PurePosixPath(path).name}"
        if identity in known_ids:
            continue
        observation["load_paths"].append(
            {
                "id": identity,
                "source": f"{path}/Cargo.toml",
                "actuator": workflow,
                "receipt": "GitHub Actions exact-head job and commit check suite",
                "standing": "PARTIAL_ALIVE",
            }
        )
    observation["load_paths"] = sorted(observation["load_paths"], key=lambda item: item["id"])
    observation["counts"]["findings"] = len(observation["findings"])
    observation["counts"]["blocking_findings"] = sum(
        item["severity"] == "Blocking" for item in observation["findings"]
    )
    return observation


def finalize_active_outputs(observation: dict[str, Any]) -> dict[str, Any]:
    """Treat every root manifest output as a generated consequence by contract."""
    owned = {
        claim["output_path"]
        for claim in observation["output_claims"]
        if claim["claim_kind"] == "active-manifest-rule" and claim["consumer"] == "."
    }
    for file in observation["files"]:
        if file["path"] in owned:
            file["authority_class"] = "GeneratedConsequence"
            file["load_bearing"] = True
    counts = Counter(file["authority_class"] for file in observation["files"])
    observation["authority_counts"] = dict(sorted(counts.items()))
    observation["counts"]["generated"] = counts.get("GeneratedConsequence", 0)
    observation["counts"]["unknown_authority"] = counts.get("UnknownAuthority", 0)
    observation.pop("observation_digest", None)
    canonical = json.dumps(observation, sort_keys=True, separators=(",", ":")).encode("utf-8")
    observation["observation_digest"] = MODEL.sha256(canonical)
    return observation


def observe(root: Path) -> dict[str, object]:
    observation = EXACT.observe(root)
    for file in observation["files"]:
        file["generated_marker"] = has_generated_header(root, str(file["path"]))
    NORMALIZER.authority_for = canonical_authority
    NORMALIZER.load_bearing = canonical_load_bearing
    normalized = NORMALIZER.normalize(observation, MODEL)
    normalized = detect_constitutional_placeholders(root, normalized)
    normalized = preserve_research_fences(root, normalized)
    normalized = admit_standalone_products(root, normalized)
    return finalize_active_outputs(normalized)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, help="repository root")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    root = (args.root or Path(__file__).resolve().parents[2]).resolve()
    return write_outputs(root, observe(root), args.check)


if __name__ == "__main__":
    raise SystemExit(main())
