#!/usr/bin/env python3
"""Observe the exact ggen Git tree and emit admitted self-hosting RDF.

This is a deliberately small bootstrap observer. It is read-only with respect to the
repository under observation and writes only beneath self-host/. Its output is consumed
by the real ggen sync pipeline and independently receipted by ggen.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import subprocess
import sys
import tomllib
from collections import Counter, defaultdict
from pathlib import Path, PurePosixPath
from typing import Any, Iterable

OBSERVER_VERSION = "ggen-self-observer-v1"
NS = "http://seanchatmangpt.github.io/packs/ggen-self-host#"
GENERATED_MARKERS = (
    "GENERATED by",
    "GENERATED:",
    "DO NOT EDIT",
    "Do not edit by hand",
    "@generated",
)
SOURCE_EXTENSIONS = {".rs", ".py", ".sh", ".js", ".ts", ".tsx", ".go", ".java", ".kt"}
TEMPLATE_EXTENSIONS = {".tera", ".tmpl", ".template", ".j2", ".jinja"}
CONFIG_EXTENSIONS = {".toml", ".yaml", ".yml", ".json", ".lock", ".ini"}
BOOTSTRAP_PREFIXES = (
    "crates/ggen-engine/src/",
    "crates/ggen-config/src/",
    "crates/ggen-graph/src/",
    "crates/praxis-core/src/",
    "crates/praxis-graphlaw/src/",
    "crates/ggen-cli/src/",
)
ARCHIVE_SEGMENTS = {"archive", "_archive", "archive_2025", "archive_ggen_core", "legacy_structure"}
SEVERITY_ORDER = {"Blocking": 0, "High": 1, "Medium": 2, "Low": 3, "Information": 4}


def run_git(root: Path, *args: str) -> str:
    result = subprocess.run(
        ["git", "-C", str(root), *args],
        check=True,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
    )
    return result.stdout.decode("utf-8", errors="strict")


def tracked_paths(root: Path) -> list[str]:
    raw = subprocess.run(
        ["git", "-C", str(root), "ls-files", "-z"],
        check=True,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
    ).stdout
    return sorted(item.decode("utf-8") for item in raw.split(b"\0") if item)


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def stable_id(prefix: str, value: str, width: int = 12) -> str:
    return f"{prefix}-{sha256(value.encode('utf-8'))[:width].upper()}"


def turtle_literal(value: object) -> str:
    text = str(value)
    text = text.replace("\\", "\\\\").replace('"', '\\"')
    text = text.replace("\r", "\\r").replace("\n", "\\n")
    return f'"{text}"'


def read_bytes(root: Path, rel: str) -> bytes:
    try:
        return (root / rel).read_bytes()
    except OSError:
        return b""


def read_text(root: Path, rel: str) -> str:
    return read_bytes(root, rel).decode("utf-8", errors="replace")


def classify(path: str, text: str) -> str:
    p = PurePosixPath(path)
    parts = set(p.parts)
    suffix = p.suffix.lower()
    if parts & ARCHIVE_SEGMENTS or any(part.startswith("archive_") for part in p.parts):
        return "Archive"
    if path.startswith("evidence/") or "/receipts/" in path or path.endswith("receipt.json"):
        return "VerificationEvidence"
    if any(marker in text for marker in GENERATED_MARKERS):
        return "GeneratedConsequence"
    if (
        path in {"Cargo.toml", "ggen.toml", "rust-toolchain.toml", "CONSTITUTION.md"}
        or path.startswith(".specify/") and suffix in {".ttl", ".rq"}
        or re.match(r"^packs/[^/]+/(ontology\.ttl|pack\.toml|gates/.*\.rq)$", path)
        or path == "self-host/ontology.ttl"
    ):
        return "AuthoredConstitution"
    if path.startswith(BOOTSTRAP_PREFIXES):
        return "BootstrapKernel"
    if path.startswith(".github/workflows/") and suffix in {".yml", ".yaml"}:
        return "Workflow"
    if suffix in TEMPLATE_EXTENSIONS:
        return "Template"
    if "/tests/" in path or "/fixtures/" in path or path.startswith("tests/"):
        return "TestFixture"
    if suffix in SOURCE_EXTENSIONS:
        return "ExecutableSource"
    if suffix == ".md" or path.startswith("docs/") or path.startswith("book/"):
        return "Documentation"
    if suffix in CONFIG_EXTENSIONS or p.name in {"justfile", "Makefile", "Makefile.toml"}:
        return "Configuration"
    return "Asset"


def is_load_bearing(path: str, authority: str) -> bool:
    if authority in {"AuthoredConstitution", "BootstrapKernel", "Workflow"}:
        return True
    if path in {"Cargo.toml", "ggen.toml", "justfile"}:
        return True
    if path.startswith(("crates/", "packs/", ".github/actions/")) and authority != "Archive":
        return True
    return False


def parse_toml(root: Path, rel: str) -> dict[str, Any] | None:
    try:
        return tomllib.loads(read_text(root, rel))
    except (tomllib.TOMLDecodeError, UnicodeError):
        return None


def normalize_output(consumer: str, path: str) -> str:
    base = PurePosixPath(consumer) if consumer != "." else PurePosixPath()
    value = PurePosixPath(path)
    if value.is_absolute() or ".." in value.parts:
        return f"UNSAFE::{path}"
    return (base / value).as_posix()


def manifest_output_claims(root: Path, paths: Iterable[str]) -> list[dict[str, str]]:
    claims: list[dict[str, str]] = []
    for rel in sorted(path for path in paths if PurePosixPath(path).name == "ggen.toml"):
        doc = parse_toml(root, rel)
        if not doc:
            continue
        consumer = PurePosixPath(rel).parent.as_posix()
        consumer = "." if consumer == "." else consumer
        generation = doc.get("generation", {})
        rules = generation.get("rules", []) if isinstance(generation, dict) else []
        for index, rule in enumerate(rules):
            if not isinstance(rule, dict) or "output_file" not in rule:
                continue
            name = str(rule.get("name", f"rule-{index:03d}"))
            output = str(rule["output_file"])
            claims.append(
                {
                    "consumer": consumer,
                    "owner": f"manifest:{rel}#{name}",
                    "output_path": normalize_output(consumer, output),
                    "claim_kind": "active-manifest-rule",
                }
            )
    return claims


def pack_output_claims(root: Path, paths: Iterable[str]) -> list[dict[str, str]]:
    claims: list[dict[str, str]] = []
    pattern = re.compile(r"(?m)^to:\s*[\"']?([^\"'\n]+)[\"']?\s*$")
    for rel in sorted(paths):
        p = PurePosixPath(rel)
        if len(p.parts) < 4 or p.parts[0] != "packs" or "templates" not in p.parts:
            continue
        text = read_text(root, rel)
        if not text.startswith("---"):
            continue
        end = text.find("\n---", 3)
        if end < 0:
            continue
        match = pattern.search(text[3:end])
        if not match:
            continue
        pack = p.parts[1]
        claims.append(
            {
                "consumer": f"pack-consumer:{pack}",
                "owner": f"pack:{pack}:{rel}",
                "output_path": match.group(1).strip(),
                "claim_kind": "pack-template",
            }
        )
    return claims


def finding(
    category: str,
    severity: str,
    summary: str,
    evidence_path: str,
    remediation: str,
    rationale: str,
    must_not: str,
    acceptance: str,
    verification: str,
) -> dict[str, Any]:
    identity = f"{category}|{evidence_path}|{summary}"
    return {
        "finding_id": stable_id("GGEN-DOGFOOD", identity, 10),
        "category": category,
        "severity": severity,
        "severity_order": SEVERITY_ORDER[severity],
        "summary": summary,
        "rationale": rationale,
        "remediation": remediation,
        "evidence_path": evidence_path,
        "must_do": remediation,
        "must_not_do": must_not,
        "acceptance_criterion": acceptance,
        "verification_command": verification,
        "status": "OPEN",
    }


def observe(root: Path) -> dict[str, Any]:
    paths = tracked_paths(root)
    revision = run_git(root, "rev-parse", "HEAD").strip()
    files: list[dict[str, Any]] = []
    text_cache: dict[str, str] = {}
    for rel in paths:
        data = read_bytes(root, rel)
        text = data.decode("utf-8", errors="replace")
        text_cache[rel] = text
        authority = classify(rel, text)
        files.append(
            {
                "path": rel,
                "digest": sha256(data),
                "size_bytes": len(data),
                "authority_class": authority,
                "load_bearing": is_load_bearing(rel, authority),
                "generated_marker": any(marker in text for marker in GENERATED_MARKERS),
            }
        )

    findings: list[dict[str, Any]] = []
    root_manifest = parse_toml(root, "Cargo.toml") or {}
    workspace = root_manifest.get("workspace", {}) if isinstance(root_manifest, dict) else {}
    members = sorted(str(item) for item in workspace.get("members", []))
    excluded = set(str(item) for item in workspace.get("exclude", []))
    cargo_manifests = sorted(path for path in paths if PurePosixPath(path).name == "Cargo.toml")
    packages: list[dict[str, str]] = []
    for rel in cargo_manifests:
        doc = parse_toml(root, rel)
        if not doc or not isinstance(doc.get("package"), dict):
            continue
        package = doc["package"]
        packages.append({"path": PurePosixPath(rel).parent.as_posix() or ".", "name": str(package.get("name", ""))})

    package_by_path = {item["path"]: item for item in packages}
    for member in members:
        if member not in package_by_path:
            findings.append(
                finding(
                    "workspace-closure", "Blocking", f"Workspace member `{member}` has no tracked Cargo package manifest.",
                    "Cargo.toml", "Repair the workspace member or restore its package manifest from admitted source.",
                    "A declared build member that does not exist makes workspace standing non-replayable.",
                    "Do not remove the member merely to force a green build without an admitted retirement decision.",
                    "Every workspace member resolves to one tracked Cargo package.",
                    "cargo metadata --no-deps --format-version 1",
                )
            )
    for item in packages:
        path = item["path"]
        if path.startswith("crates/") and path not in members and path not in excluded:
            findings.append(
                finding(
                    "workspace-closure", "High", f"Tracked crate `{path}` is outside the workspace and exclude set.",
                    f"{path}/Cargo.toml", "Classify the crate as an admitted member, explicit exclusion, or archive.",
                    "A crate on disk without workspace standing is an ambiguous executable surface.",
                    "Do not silently leave live source outside all build and exclusion boundaries.",
                    "The crate is represented exactly once in workspace members, exclusions, or an archive decision.",
                    "python3 self-host/scripts/observe_repository.py --check",
                )
            )
    names: dict[str, list[str]] = defaultdict(list)
    for item in packages:
        names[item["name"]].append(item["path"])
    for name, owners in sorted(names.items()):
        if name and len(owners) > 1:
            findings.append(
                finding(
                    "workspace-identity", "Blocking", f"Cargo package identity `{name}` has competing owners: {', '.join(owners)}.",
                    "Cargo.toml", "Give every active Cargo package one unique package identity.",
                    "Duplicate package identities make dependency and release projections ambiguous.",
                    "Do not rely on path context to distinguish equal package identities.",
                    "No two active Cargo manifests declare the same package name.",
                    "cargo metadata --no-deps --format-version 1",
                )
            )

    pack_dirs = sorted({PurePosixPath(path).parts[1] for path in paths if path.startswith("packs/") and len(PurePosixPath(path).parts) > 2})
    for pack in pack_dirs:
        required = [f"packs/{pack}/pack.toml", f"packs/{pack}/ontology.ttl"]
        for required_path in required:
            if required_path not in paths:
                findings.append(
                    finding(
                        "pack-contract", "Blocking", f"Pack `{pack}` is missing `{PurePosixPath(required_path).name}`.",
                        f"packs/{pack}", "Complete or explicitly retire the pack contract.",
                        "A pack directory without identity and ontology cannot participate in lawful composition.",
                        "Do not infer pack standing from the directory name or README alone.",
                        "Every active pack has one pack.toml and one parseable ontology.ttl.",
                        "python3 self-host/scripts/observe_repository.py --check",
                    )
                )

    claims = manifest_output_claims(root, paths) + pack_output_claims(root, paths)
    active_claims = [claim for claim in claims if claim["claim_kind"] == "active-manifest-rule"]
    active_by_output: dict[tuple[str, str], list[str]] = defaultdict(list)
    for claim in active_claims:
        active_by_output[(claim["consumer"], claim["output_path"])].append(claim["owner"])
    for (consumer, output), owners in sorted(active_by_output.items()):
        if len(owners) > 1:
            findings.append(
                finding(
                    "output-ownership", "Blocking", f"Consumer `{consumer}` has {len(owners)} writers for `{output}`.",
                    "ggen.toml", "Collapse the output to one authoritative projection owner.",
                    "Multiple writers are competing actuators and make receipts non-attributable.",
                    "Do not resolve the collision by relying on generation order or last-writer-wins behavior.",
                    "Every active output path has exactly one generation owner.",
                    "python3 self-host/scripts/observe_repository.py --check",
                )
            )

    claimed_outputs = {claim["output_path"] for claim in active_claims if not claim["output_path"].startswith("UNSAFE::")}
    for file in files:
        if file["generated_marker"] and file["path"] not in claimed_outputs:
            findings.append(
                finding(
                    "generated-ownership", "Blocking", f"Generated-marked file `{file['path']}` has no active manifest output owner.",
                    file["path"], "Bind the file to admitted ontology/template law or reclassify it honestly as authored bootstrap code.",
                    "A generated marker without a live generator is false authority and cannot be independently regenerated.",
                    "Do not preserve a generated comment as a substitute for an executable projection path.",
                    "A clean checkout can regenerate the exact file from one named owner and verify identical bytes.",
                    "python3 self-host/scripts/observe_repository.py --check",
                )
            )
    for claim in active_claims:
        output = claim["output_path"]
        if not output.startswith("UNSAFE::") and output not in paths:
            findings.append(
                finding(
                    "generated-output", "High", f"Declared output `{output}` is absent from the tracked tree.",
                    claim["owner"], "Run the owning projection and either commit the admitted consequence or remove the stale claim.",
                    "A declared consequence with no artifact is an open manufacturing obligation.",
                    "Do not hand-create a placeholder file to satisfy existence checks.",
                    "The owning generation rule produces the artifact and second generation is byte-identical.",
                    "ggen sync run && ggen receipt verify",
                )
            )

    root_markdown = sorted(path for path in paths if "/" not in path and path.endswith(".md"))
    allowed_root_markdown = {"README.md", "CHANGELOG.md", "CONTRIBUTING.md", "CONTRIBUTORS.md", "CODE_OF_CONDUCT.md", "SECURITY.md", "AGENTS.md", "CLAUDE.md", "CONSTITUTION.md", "SKILLS.md"}
    noncanonical_markdown = [path for path in root_markdown if path not in allowed_root_markdown]
    if noncanonical_markdown:
        findings.append(
            finding(
                "repository-layout", "Medium", f"{len(noncanonical_markdown)} noncanonical Markdown files remain at repository root.",
                noncanonical_markdown[0], "Move each live document to a governed docs path or archive it through one migration map.",
                "The repository violates its own no-root-files rule and agents cannot distinguish current law from historical reports.",
                "Do not bulk-delete or move files until load-path references are observed and rewritten.",
                "Every nonstandard root document has one admitted destination and no broken inbound references.",
                "python3 self-host/scripts/observe_repository.py --check",
            )
        )

    loose_templates = sorted(path for path in paths if path.startswith("templates/") and PurePosixPath(path).suffix.lower() in TEMPLATE_EXTENSIONS)
    if loose_templates:
        findings.append(
            finding(
                "template-authority", "High", f"{len(loose_templates)} root templates remain outside pack-scoped ownership.",
                "templates/", "Trace every root template consumer, migrate live templates to owning packs, and archive only proven-dead templates.",
                "Two template authority systems permit orphaned generators and hidden consumers.",
                "Do not delete or relocate a template before a load-path witness proves its consumers and output equivalence.",
                "Every live template belongs to exactly one pack and regenerates its prior consumer bytes.",
                "python3 self-host/scripts/observe_repository.py --check",
            )
        )

    remediation_scripts = sorted(
        path for path in paths
        if path.startswith("scripts/") and re.search(r"(^|/)(fix[_-]|patch[_-]|full_recovery|remove_duplicate)", path)
    )
    if remediation_scripts:
        findings.append(
            finding(
                "script-authority", "Medium", f"{len(remediation_scripts)} historical remediation scripts share the live scripts namespace.",
                "scripts/", "Classify script load paths, retain live tools, and move zero-consumer historical remediations under one archive boundary.",
                "Operators and coding agents cannot determine which scripts have current standing from location alone.",
                "Do not archive a script that is referenced by CI, justfile, release automation, or a documented operational procedure.",
                "Every top-level live script has an observed consumer; every historical script is isolated under the archive boundary.",
                "python3 self-host/scripts/observe_repository.py --check",
            )
        )

    archive_roots = sorted({PurePosixPath(path).parts[1] for path in paths if path.startswith("examples/") and len(PurePosixPath(path).parts) > 1 and (PurePosixPath(path).parts[1] in ARCHIVE_SEGMENTS or PurePosixPath(path).parts[1].startswith("archive_"))})
    if len(archive_roots) > 1:
        findings.append(
            finding(
                "archive-authority", "Medium", f"Examples use competing archive roots: {', '.join(archive_roots)}.",
                "examples/", "Migrate all archived examples under one canonical archive root with a complete old-to-new map.",
                "Multiple archive conventions make dead/live classification nondeterministic.",
                "Do not flatten or delete archived examples; preserve original provenance beneath the canonical root.",
                "Exactly one archive root remains and every previous path has a documented deterministic mapping.",
                "python3 self-host/scripts/observe_repository.py --check",
            )
        )

    if ".specify/repo-facts.ttl" in paths and "Facts transcribed" in text_cache.get(".specify/repo-facts.ttl", ""):
        findings.append(
            finding(
                "observation-authority", "Blocking", "`.specify/repo-facts.ttl` manually transcribes repository facts that can be observed mechanically.",
                ".specify/repo-facts.ttl", "Split authored architectural judgments from observed facts and project live counts/identities from the self-host observation graph.",
                "Copying Cargo, pack, and workflow facts into RDF creates a second mutable source of truth and has already produced stale generated tables.",
                "Do not refresh the copied counts by hand or regenerate prose from another hand-maintained snapshot.",
                "All mechanical repository facts are emitted by the observer; authored RDF contains only policy and judgment.",
                "python3 self-host/scripts/observe_repository.py --check && cd self-host && ../target/debug/ggen sync run",
            )
        )

    if "fn inject_default_verbs" in text_cache.get("crates/ggen-cli/src/lib.rs", ""):
        findings.append(
            finding(
                "cli-authority", "High", "Default CLI verb aliases are maintained in handwritten dispatch code.",
                "crates/ggen-cli/src/lib.rs", "Declare noun defaults in the CLI ontology and manufacture the alias table and tests from one command graph.",
                "The public CLI is partially ontology-generated while compatibility aliases remain a separate handwritten registry.",
                "Do not add another noun/default pair directly to inject_default_verbs.",
                "Adding a default verb to ontology regenerates dispatch and its positive/negative CLI proofs with no handwritten branch.",
                "cargo test -p ggen-cli-lib --test cli_boundary",
            )
        )

    codeowners = any(path.endswith("CODEOWNERS") for path in paths)
    if not codeowners:
        findings.append(
            finding(
                "contribution-governance", "High", "No CODEOWNERS file is present in the tracked tree.",
                ".github/", "Generate CODEOWNERS from the repository authority graph and place external branch protection behind an authorization packet.",
                "Ownership policy is currently implicit and cannot be checked against changed paths.",
                "Do not invent owners from usernames or enable external branch protection without explicit authorization.",
                "Every load-bearing path has a declared review authority and the generated CODEOWNERS bytes match the graph.",
                "python3 self-host/scripts/observe_repository.py --check",
            )
        )

    load_paths = [
        {"id": "generation", "source": ".specify + packs + ggen.toml", "actuator": "ggen sync run", "receipt": ".ggen-v2/receipt.json", "standing": "PARTIAL_ALIVE"},
        {"id": "self-generation", "source": "self-host/ontology.ttl", "actuator": "ggen sync run in self-host", "receipt": "self-host/.ggen-v2/receipt.json", "standing": "PARTIAL_ALIVE"},
        {"id": "contribution", "source": "branch and pull request", "actuator": "GitHub merge", "receipt": "GitHub checks and merge commit", "standing": "PARTIAL_ALIVE"},
        {"id": "release", "source": "release ontology and tag", "actuator": "protected release workflows", "receipt": "release attestations", "standing": "PARTIAL_ALIVE"},
        {"id": "constitution", "source": "ggen-constitution-pack ontology", "actuator": "admission law", "receipt": "sync receipt and law evidence", "standing": "PARTIAL_ALIVE"},
        {"id": "fleet", "source": "github-actions and gh-terraform packs", "actuator": "externally authorized BRCE path", "receipt": "fleet plan/apply receipts", "standing": "UNKNOWN"},
    ]

    findings = sorted(
        {item["finding_id"]: item for item in findings}.values(),
        key=lambda item: (item["severity_order"], item["category"], item["finding_id"]),
    )
    authority_counts = Counter(file["authority_class"] for file in files)
    generated_count = authority_counts.get("GeneratedConsequence", 0)
    workflow_count = sum(file["authority_class"] == "Workflow" for file in files)
    template_count = sum(file["authority_class"] == "Template" for file in files)
    script_count = sum(file["path"].startswith("scripts/") for file in files)
    blocking = sum(item["severity"] == "Blocking" for item in findings)
    unknown = authority_counts.get("UnknownAuthority", 0)

    observation: dict[str, Any] = {
        "schema": "ggen-self-host-observation-v1",
        "observer_version": OBSERVER_VERSION,
        "repository": "seanchatmangpt/ggen",
        "revision": revision,
        "counts": {
            "files": len(files),
            "cargo_packages": len(packages),
            "workspace_members": len(members) + (1 if root_manifest.get("package") else 0),
            "packs": len(pack_dirs),
            "workflows": workflow_count,
            "templates": template_count,
            "scripts": script_count,
            "root_markdown": len(root_markdown),
            "generated": generated_count,
            "findings": len(findings),
            "blocking_findings": blocking,
            "unknown_authority": unknown,
        },
        "authority_counts": dict(sorted(authority_counts.items())),
        "workspace_members": members,
        "cargo_packages": packages,
        "packs": pack_dirs,
        "files": files,
        "output_claims": sorted(claims, key=lambda item: (item["consumer"], item["output_path"], item["owner"])),
        "load_paths": load_paths,
        "findings": findings,
    }
    canonical = json.dumps(observation, sort_keys=True, separators=(",", ":")).encode("utf-8")
    observation["observation_digest"] = sha256(canonical)
    return observation


