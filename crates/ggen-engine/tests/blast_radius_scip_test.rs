//! E80-04: SCIP-backed blast-radius gate, end-to-end over a real ggen-scip
//! emit. Chicago: real index emit → real query handle → radius → gate.
//!
//! Chain: `a() -> b() -> c()` in a generated-surface fixture; writing `c`
//! impacts `b` then `a` through SCIP reference inversion.

#![allow(
    clippy::unwrap_used,
    clippy::expect_used,
    clippy::panic,
    clippy::similar_names
)]
use ggen_engine::blast_radius::{
    admit_write, compute, Admission, PlannedWrite, RadiusOrigin, ScipGraph, SymbolGraph, WritePlan,
};
use ggen_scip::query::Query;

/// Write the a→b→c fixture under `root` in ggen-scip's discoverable layout
/// (`crates/<pkg>/src/*.rs`, generated banner in the first 5 lines).
fn write_fixture(root: &std::path::Path) -> String {
    let src = root.join("crates/fixture/src");
    std::fs::create_dir_all(&src).expect("mkdir");
    // [package] name anchors the SCIP symbol package segment (emit falls back
    // to an empty package without a Cargo.toml ancestor).
    std::fs::write(
        root.join("crates/fixture/Cargo.toml"),
        "[package]\nname = \"fixture\"\nversion = \"0.1.0\"\n",
    )
    .expect("write manifest");
    let rel = "crates/fixture/src/chain.rs";
    std::fs::write(
        root.join(rel),
        r"// Generated by ggen: SCIP blast-radius fixture (E80-04).
fn a() { b(); }
fn b() { c(); }
fn c() {}
",
    )
    .expect("write fixture");
    rel.to_string()
}

/// Emit the real SCIP index and build the adapter.
fn scip_graph(root: &std::path::Path) -> ScipGraph {
    ggen_scip::emit::emit(root).expect("emit");
    let query = Query::open_root(root).expect("open query");
    ScipGraph::from_query(&query)
}

fn sym(name: &str) -> String {
    format!("ggen fixture chain.{name}")
}

#[test]
fn scip_callers_inverted_and_radius_of_b_is_a() {
    let tmp = tempfile::TempDir::new().expect("tmpdir");
    let root = tmp.path();
    let rel = write_fixture(root);
    let graph = scip_graph(root);

    // Inverted references: callers(b) = {a}, callers(c) = {b}, callers(a) = {}.
    assert_eq!(graph.callers_of(&sym("b")), vec![sym("a")]);
    assert_eq!(graph.callers_of(&sym("c")), vec![sym("b")]);
    assert!(graph.callers_of(&sym("a")).is_empty());

    // Subtype encoding gap: SCIP index carries no subtype relations.
    assert!(graph.subtypes_of(&sym("a")).is_empty());

    // Definition sites resolve to the fixture document.
    let loc = graph.def_site(&sym("c")).expect("c defined");
    assert_eq!(loc.path, rel);
    assert_eq!(loc.symbol, sym("c"));
    assert!(graph.def_site(&sym("missing")).is_none());

    // BlastRadius(b) = {a}, CallersStar.
    let radius = compute(&sym("b"), &graph, 16);
    assert_eq!(radius.symbols.len(), 1, "radius: {:?}", radius.symbols);
    assert_eq!(
        radius.symbols.get(&sym("a")),
        Some(&RadiusOrigin::CallersStar)
    );
    assert!(radius
        .edges
        .contains(&format!("{} -> {}", sym("b"), sym("a"))));
    assert!(!radius.truncated);
}

#[test]
fn scip_admit_write_refused_end_to_end() {
    let tmp = tempfile::TempDir::new().expect("tmpdir");
    let root = tmp.path();
    let rel = write_fixture(root);
    let graph = scip_graph(root);

    // Plan writes c (defined in the fixture); the fixture path is protected.
    // Expected violations: c itself at depth 0 (written path protected), plus
    // radius symbols b (depth 1) and a (depth 2) whose def sites land on the
    // protected path via callers* traversal.
    let plan = WritePlan::new(vec![PlannedWrite {
        path: rel.clone(),
        symbols: vec![sym("c")],
    }]);
    let protected = vec![rel.clone()];

    match admit_write(&plan, &graph, &protected) {
        Admission::Refused {
            violations,
            receipt,
            ..
        } => {
            assert_eq!(receipt.verdict, "REFUSED");
            let by_sym: Vec<(&str, usize)> = violations
                .iter()
                .map(|v| (v.radius_symbol.as_str(), v.depth))
                .collect();
            assert!(
                by_sym.contains(&(sym("c").as_str(), 0))
                    && by_sym.contains(&(sym("b").as_str(), 1))
                    && by_sym.contains(&(sym("a").as_str(), 2)),
                "violations: {by_sym:?}"
            );
        }
        other => panic!("expected REFUSED, got {other:?}"),
    }
}

#[test]
fn scip_admit_write_alive_outside_protected_surface() {
    let tmp = tempfile::TempDir::new().expect("tmpdir");
    let root = tmp.path();
    write_fixture(root);
    let graph = scip_graph(root);

    // Same write, protected surface elsewhere: ALIVE with full radius slice.
    let plan = WritePlan::new(vec![PlannedWrite {
        path: "crates/fixture/src/chain.rs".to_string(),
        symbols: vec![sym("c")],
    }]);
    match admit_write(&plan, &graph, &["ggen-engine/src/sync.rs".to_string()]) {
        Admission::Alive {
            radius, receipt, ..
        } => {
            assert_eq!(receipt.verdict, "ALIVE");
            assert_eq!(radius.symbols.len(), 3, "radius: {:?}", radius.symbols); // c (Written) + b, a (CallersStar)
            assert_eq!(
                radius.symbols.get(&sym("b")),
                Some(&RadiusOrigin::CallersStar)
            );
            assert_eq!(
                radius.symbols.get(&sym("a")),
                Some(&RadiusOrigin::CallersStar)
            );
        }
        other => panic!("expected ALIVE, got {other:?}"),
    }
}

#[test]
fn scip_two_emits_identical_radius() {
    // Two independent emits over identical fixture roots -> byte-identical
    // canonical index JSON, and identical computed radius + gate verdict.
    let tmp_a = tempfile::TempDir::new().expect("tmpdir a");
    let tmp_b = tempfile::TempDir::new().expect("tmpdir b");
    write_fixture(tmp_a.path());
    write_fixture(tmp_b.path());

    let index_a = ggen_scip::emit::emit(tmp_a.path()).expect("emit a");
    let index_b = ggen_scip::emit::emit(tmp_b.path()).expect("emit b");
    let json_a = ggen_scip::canonical_json(&index_a).expect("canonical a");
    let json_b = ggen_scip::canonical_json(&index_b).expect("canonical b");
    // project_root differs by tmpdir path; strip metadata for the byte
    // comparison — document payloads must be identical.
    let docs_a = serde_json::to_string(&index_a.documents).expect("docs a");
    let docs_b = serde_json::to_string(&index_b.documents).expect("docs b");
    assert_eq!(docs_a, docs_b);

    let graph_a = ScipGraph::from_query(&Query::from_index(index_a));
    let graph_b = ScipGraph::from_query(&Query::from_index(index_b));

    let radius_a = compute(&sym("c"), &graph_a, 16);
    let radius_b = compute(&sym("c"), &graph_b, 16);
    assert_eq!(radius_a, radius_b);

    let plan = WritePlan::new(vec![PlannedWrite {
        path: "crates/fixture/src/chain.rs".to_string(),
        symbols: vec![sym("c")],
    }]);
    let prot: Vec<String> = vec!["crates/fixture/src/chain.rs".to_string()];
    assert_eq!(
        admit_write(&plan, &graph_a, &prot),
        admit_write(&plan, &graph_b, &prot)
    );
    // Silence unused warning path for canonical json (used for determinism
    // receipt evidence).
    assert!(!json_a.is_empty() && !json_b.is_empty());
}
