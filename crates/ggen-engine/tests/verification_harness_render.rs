//! Golden render test for the opt-in `[generation.verification_harness]`
//! template (`templates/verification-harness.tera.tmpl`).
//!
//! S2's lesson: authoring a template is not rendering it. This test renders
//! through the REAL pipeline (`ggen_engine::sync::sync` — the same tera
//! one-off render `generation_rules.rs` performs) and asserts on the actual
//! on-disk bytes of `.ggen-v2/verify/{tsconfig.verify.json,verify.mjs}`,
//! never on the template source text.
//!
//! Chicago: real collaborator (real sync over a real temp project), assert
//! final on-disk state.

#![allow(clippy::unwrap_used, clippy::expect_used, clippy::panic)]

use tempfile::TempDir;

const ONTOLOGY: &str = r#"
@prefix ex: <http://example.org/> .
ex:alice ex:name "alice" .
"#;

fn write_project(dir: &std::path::Path, generation_body: &str) {
    let manifest = format!(
        "[project]\nname = \"gendemo\"\nversion = \"0.1.0\"\n\n[ontology]\nsource = \"ontology.ttl\"\n\n{generation_body}"
    );
    std::fs::write(dir.join("ggen.toml"), manifest).expect("write ggen.toml");
    std::fs::write(dir.join("ontology.ttl"), ONTOLOGY).expect("write ontology.ttl");
}

fn sync_flag(generation_body: &str) -> (TempDir, ggen_engine::sync::SyncReport) {
    let dir = TempDir::new().expect("tempdir");
    write_project(dir.path(), generation_body);
    let report = ggen_engine::sync::sync(
        dir.path(),
        ggen_engine::sync::SyncOptions {
            skip_ea_admission: true,
            ..Default::default()
        },
    )
    .expect("sync");
    (dir, report)
}

#[test]
fn flag_on_renders_tsconfig_verify_json_and_verify_mjs() {
    let (dir, report) = sync_flag(
        "[[generation.rules]]\nname = \"types\"\nquery = { inline = \"SELECT ?name WHERE { ?s <http://example.org/name> ?name } ORDER BY ?name\" }\ntemplate = { inline = \"export const names = [\\\"{{ row.name }}\\\"];\" }\noutput_file = \"src/types/names.ts\"\n\n[generation.verification_harness]\npeers = [\"xstate\"]\n",
    );

    let tsconfig = std::fs::read_to_string(dir.path().join(".ggen-v2/verify/tsconfig.verify.json"))
        .expect("read tsconfig.verify.json");
    let verify_mjs = std::fs::read_to_string(dir.path().join(".ggen-v2/verify/verify.mjs"))
        .expect("read verify.mjs");

    // Golden shapes: the two harness files, with manifest-derived aliases.
    assert!(
        tsconfig.contains("\"@generated/src_types\": [\"./src/types\"]"),
        "tsconfig must carry the manifest-derived alias, got:\n{tsconfig}"
    );
    assert!(tsconfig.contains("\"./src/types/**/*\""));
    // The emitted tsconfig must be valid JSON, not scaffolding leaking through.
    let parsed: serde_json::Value = serde_json::from_str(&tsconfig)
        .unwrap_or_else(|e| panic!("tsconfig.verify.json is not valid JSON: {e}\n{tsconfig}"));
    assert_eq!(parsed["compilerOptions"]["strict"], serde_json::json!(true));
    assert_eq!(
        parsed["compilerOptions"]["paths"]["@generated/src_types"][0],
        serde_json::json!("./src/types")
    );

    assert!(verify_mjs.contains("npx tsc -p tsconfig.verify.json"));
    assert!(verify_mjs.contains("xstate"));
    assert!(
        verify_mjs.starts_with("// Generated by ggen ggen@"),
        "verify.mjs header defect, first 120 bytes: {:?}",
        &verify_mjs[..verify_mjs.len().min(120)]
    );

    // Receipt-visible writes.
    assert!(report.written.contains(&std::path::PathBuf::from(
        ".ggen-v2/verify/tsconfig.verify.json"
    )));
    assert!(report
        .written
        .contains(&std::path::PathBuf::from(".ggen-v2/verify/verify.mjs")));
}

#[test]
fn flag_off_renders_nothing() {
    let (dir, report) = sync_flag(
        "[[generation.rules]]\nname = \"types\"\nquery = { inline = \"SELECT ?name WHERE { ?s <http://example.org/name> ?name } ORDER BY ?name\" }\ntemplate = { inline = \"export const names = [];\" }\noutput_file = \"src/types/names.ts\"\n",
    );
    assert!(!dir.path().join(".ggen-v2/verify").exists());
    assert_eq!(report.written.len(), 1); // only the rule output
}
