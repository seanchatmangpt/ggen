/// A single-file transactional edit commitment (R80-5 shape, re-declared
/// locally — see module docs for the disclosure).
#[derive(Debug, Clone, PartialEq, Eq, serde::Deserialize, serde::Serialize)]
pub struct FileEdit {
    /// Working-tree-relative path of the target file.
    pub path: String,
    /// Bytes present before the edit; `None` = file did not exist.
    pub before_bytes: Option<Vec<u8>>,
    /// Bytes to be present after the edit.
    pub after_bytes: Vec<u8>,
    /// SHA-256 (hex) of `before_bytes` — of the empty image when absent.
    pub before_sha256: String,
    /// SHA-256 (hex) of `after_bytes`.
    pub after_sha256: String,
}

/// Working-tree context the batch binds against.
#[derive(Debug, Clone)]
pub struct TreeContext {
    /// Root of the working tree on disk (evidence verification reads real
    /// bytes under this root).
    pub tree_root: PathBuf,
    /// owner/repo form (validated by admission's `@repo` law).
    pub repository: String,
    /// 40-hex base SHA of the working tree.
    pub base_sha: String,
    /// Paths admission must never propose an edit against.
    pub protected_paths: Vec<String>,
}

/// One edit batch: the proposal input.
#[derive(Debug, Clone)]
pub struct EditBatch {
    /// Human description; becomes the WorkOrder identity/title source.
    pub description: String,
    /// The edits in the batch.
    pub edits: Vec<FileEdit>,
    /// The acceptance command: how the edit is verified after application.
    pub verification_command: String,
    /// The falsifier: the mutation that would detect regression of this
    /// edit's purpose.
    pub mutation_description: String,
}

/// Typed bridge refusals, each carrying remediation.
#[derive(Debug, Clone, PartialEq, Eq, thiserror::Error)]
pub enum BridgeRefusal {
    #[error(
        "EmptyBatch: no edits proposed — remediation: supply at least one FileEdit with \
         non-empty path and well-formed before/after commitments"
    )]
    EmptyBatch,

    #[error(
        "ProtectedPath: {path} is on the protected surface — remediation: remove the edit \
         from the batch or obtain explicit authority; the bridge never proposes work \
         against protected paths"
    )]
    ProtectedPath { path: String },

    #[error(
        "TamperedEvidence: {path} — remediation: re-capture the FileEdit against the \
         current working tree; the on-disk state moved after capture"
    )]
    TamperedEvidence { path: String },

    #[error(
        "MissingTree: {0} — remediation: point tree_root at an existing directory; \
         evidence verification reads real bytes under it"
    )]
    MissingTree(String),

    #[error(
        "IllegalTransition: {detail} — remediation: only sealed transitions produced by \
         the admission loop may be journaled; re-run the loop rather than hand-building \
         chain records"
    )]
    IllegalTransition { detail: String },
}

/// Symbol graph seam (re-declared locally — see module docs). Backed by
/// the real `ggen-scip` index via [`ScipGraph`]; [`VectorGraph`] is the
/// deterministic test-only fixture seed (disclosed, retained).
pub trait SymbolGraph {
    /// The transitive symbol ids reachable from an edit to `path`.
    fn blast_radius(&self, path: &str) -> Vec<String>;
}

/// SCIP-backed [`SymbolGraph`]: wraps a real `ggen-scip` index (R80-3
/// emitter/query pub APIs, consumed through the disclosed path
/// dependency) and answers [`SymbolGraph::blast_radius`] from real
/// definition/reference occurrences.
///
/// Semantics mirror the fixture's law: seeds are the wire symbols
/// *defined in* the edited document (`doc.path == path`); the radius is
/// the transitive closure over "symbols referenced by the defining
/// document of each reached symbol". Deterministic: BTreeSet ordering
/// throughout.
pub struct ScipGraph {
    /// wire symbol -> path of the document defining it.
    def_doc: BTreeMap<String, String>,
    /// document path -> wire symbols that document references.
    doc_refs: BTreeMap<String, BTreeSet<String>>,
}

impl ScipGraph {
    /// Build the graph from an in-memory [`ggen_scip::Index`].
    pub fn from_index(index: ggen_scip::Index) -> Self {
        let mut def_doc: BTreeMap<String, String> = BTreeMap::new();
        let mut doc_refs: BTreeMap<String, BTreeSet<String>> = BTreeMap::new();
        for doc in &index.documents {
            for occ in &doc.occurrences {
                if occ.roles & ggen_scip::ROLE_DEFINITION != 0 {
                    def_doc
                        .entry(occ.symbol.clone())
                        .or_insert_with(|| doc.path.clone());
                } else {
                    doc_refs
                        .entry(doc.path.clone())
                        .or_default()
                        .insert(occ.symbol.clone());
                }
            }
        }
        ScipGraph { def_doc, doc_refs }
    }

    /// Open `<root>/.ggen/scip.json` through ggen-scip's query API
    /// (`ggen_scip::query::Query`), then index it.
    pub fn open_root(root: &std::path::Path) -> std::io::Result<Self> {
        let q = ggen_scip::query::Query::open_root(root)?;
        Ok(Self::from_index(q.index().clone()))
    }

    /// Underlying index document count (witness surface for tests).
    pub fn document_count(&self) -> usize {
        self.doc_refs.len()
    }
}

impl SymbolGraph for ScipGraph {
    fn blast_radius(&self, path: &str) -> Vec<String> {
        // Seeds: wire symbols defined in the edited document.
        let mut seen: BTreeSet<String> = BTreeSet::new();
        let mut frontier: Vec<String> = self
            .def_doc
            .iter()
            .filter(|(_, doc)| doc.as_str() == path)
            .map(|(sym, _)| sym.clone())
            .collect();
        // Transitive walk: neighbors of a reached symbol are the symbols
        // referenced by that symbol's defining document. Bounded by the
        // symbol table size (acyclic guard, same as the fixture).
        let budget = self.def_doc.len() + 1;
        let mut steps = 0usize;
        while let Some(sym) = frontier.pop() {
            if !seen.insert(sym.clone()) {
                continue;
            }
            steps += 1;
            if steps > budget {
                break;
            }
            if let Some(doc) = self.def_doc.get(&sym) {
                if let Some(refs) = self.doc_refs.get(doc) {
                    frontier.extend(refs.iter().cloned());
                }
            }
        }
        seen.into_iter().collect()
    }
}

/// Real (non-mock) fixture implementation of [`SymbolGraph`]: an explicit
/// caller→callee edge table walked to transitive closure. Chicago-clean:
/// it is a hand-written real implementation, not a double of an owned
/// collaborator. DISCLOSED test-only fallback (E80-03): production
/// callers pass a [`ScipGraph`]; the fixture remains as the deterministic
/// test seed (small known edge tables) — not deleted per lane contract.
pub struct VectorGraph {
    /// `symbol -> callees` edges, where a symbol is "defined in" a path
    /// when its id starts with `path`.
    pub edges: Vec<(String, String)>,
}

impl SymbolGraph for VectorGraph {
    fn blast_radius(&self, path: &str) -> Vec<String> {
        // Seeds: symbols defined in the edited path.
        let seeds: Vec<String> = self
            .edges
            .iter()
            .filter(|(caller, _)| caller.starts_with(path))
            .map(|(caller, _)| caller.clone())
            .collect();
        // Transitive callers-star: walk outward from each seed, collecting
        // callees, bounded by the edge count (acyclic guard).
        let mut seen: BTreeSet<String> = BTreeSet::new();
        let mut frontier = seeds;
        let mut budget = self.edges.len() + 1;
        while let Some(sym) = frontier.pop() {
            if !seen.insert(sym.clone()) {
                continue;
            }
            budget -= 1;
            if budget == 0 {
                break;
            }
            for (caller, callee) in &self.edges {
                if *caller == sym {
                    frontier.push(callee.clone());
                }
            }
        }
        seen.into_iter().collect()
    }
}

