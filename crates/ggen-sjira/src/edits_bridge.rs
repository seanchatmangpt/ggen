/// Result of binding a batch's sha256 commitments to the real tree.
#[derive(Debug, Clone)]
pub struct EvidenceCheck {
    /// Paths whose on-disk state matched their before-commitment.
    pub verified_paths: Vec<String>,
    /// Batch digest: sha256 over canonical JSON of sorted
    /// (path, before_sha256, after_sha256) triples.
    pub batch_digest: String,
}

/// SHA-256 of a byte slice, hex-encoded (no `hex` crate — same dependency
/// floor as work_order.rs).
fn sha256_hex(bytes: &[u8]) -> String {
    let mut h = Sha256::new();
    h.update(bytes);
    h.finalize().iter().map(|b| format!("{b:02x}")).collect()
}

/// Empty-image sha256 (`sha256(&[])`) — the commitment for an absent file.
pub fn empty_sha256() -> String {
    sha256_hex(&[])
}

/// True when `path` equals `candidate` or lives under it
/// (working-tree-relative, '/' separators only).
fn path_is_or_under(candidate: &str, path: &str) -> bool {
    candidate == path || (candidate.ends_with('/') && path.starts_with(candidate))
}

/// Verify one batch's evidence against the real working tree, refusing the
/// first tamper. A tamper is either (a) the file's on-disk state no longer
/// matches the before-commitment (present-on-disk vs absent-in-commitment
/// or a hash divergence — the tree moved after capture), or (b)
/// `after_sha256` does not hash the `after_bytes` the batch carries
/// (self-inconsistent commitment).
pub fn verify_evidence(
    batch: &EditBatch, ctx: &TreeContext,
) -> Result<EvidenceCheck, BridgeRefusal> {
    if batch.edits.is_empty() {
        return Err(BridgeRefusal::EmptyBatch);
    }
    if !ctx.tree_root.is_dir() {
        return Err(BridgeRefusal::MissingTree(
            ctx.tree_root.display().to_string(),
        ));
    }
    let mut verified_paths = Vec::new();
    for edit in &batch.edits {
        if ctx
            .protected_paths
            .iter()
            .any(|p| path_is_or_under(p, &edit.path))
        {
            return Err(BridgeRefusal::ProtectedPath {
                path: edit.path.clone(),
            });
        }
        let abs = ctx.tree_root.join(&edit.path);
        let on_disk = std::fs::read(&abs).ok();
        let before_matches = match (&edit.before_bytes, &on_disk) {
            // Captured as absent, and absent on disk.
            (None, None) => edit.before_sha256 == empty_sha256(),
            // Captured as present; on disk and hashing to the commitment.
            (Some(_), Some(bytes)) => sha256_hex(bytes) == edit.before_sha256,
            // Capture and disk disagree about existence — tree moved.
            _ => false,
        };
        if !before_matches {
            return Err(BridgeRefusal::TamperedEvidence {
                path: edit.path.clone(),
            });
        }
        if sha256_hex(&edit.after_bytes) != edit.after_sha256 {
            return Err(BridgeRefusal::TamperedEvidence {
                path: edit.path.clone(),
            });
        }
        verified_paths.push(edit.path.clone());
    }
    let mut triples: Vec<(String, Value)> = batch
        .edits
        .iter()
        .map(|e| {
            let v = serde_json::json!({
                "after_sha256": e.after_sha256,
                "before_sha256": e.before_sha256,
                "path": e.path,
            });
            (e.path.clone(), v)
        })
        .collect();
    triples.sort_by(|a, b| a.0.cmp(&b.0));
    let mut h = Sha256::new();
    for (_, v) in &triples {
        h.update(canonical(v).to_string().as_bytes());
    }
    let batch_digest = format!(
        "sha256:{}",
        h.finalize()
            .iter()
            .map(|b| format!("{b:02x}"))
            .collect::<String>()
    );
    Ok(EvidenceCheck {
        verified_paths,
        batch_digest,
    })
}

