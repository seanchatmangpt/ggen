//! Edits → sj:WorkOrder admission bridge (reverse-80/20 §5) — closes the
//! admission-controller loop: a batch of proposed transactional file edits
//! becomes WorkOrder candidates, flows through `admit_work_order`, and the
//! outcome (admitted OR refused) is journaled as a chained transition.
//!
//! Local re-declarations, disclosed for later unification (this lane owns
//! only this file + its test):
//!
//! - [`FileEdit`] mirrors ggen-engine's R80-5 transactional shape
//!   (`crates/ggen-engine/src/transactional.rs::FileEdit`). Re-declared
//!   locally per lane contract; the engine file was mid-flight during this
//!   lane's window, so no cross-crate import was lawful.
//! - [`SymbolGraph`] mirrors ggen-engine's `blast_radius.rs` trait. A
//!   concrete handle is OPTIONAL: when present, the batch's blast radius is
//!   attached as required evidence; when absent, only path-scope evidence
//!   is carried. The seam is now backed by the real `ggen-scip` index via
//!   [`ScipGraph`] (path dependency, disclosed — E80-03): a real SCIP
//!   index over real generated bytes. [`VectorGraph`] remains only as the
//!   deterministic test-only fixture seed.
//! - [`BridgeJournal`] reimplements the blake3 transition-chain law
//!   (`hash_n = blake3(prev_hash ‖ canonical_json(body_n))`) because the
//!   sibling receipts.rs (L7) was mid-flight/corrupted during this lane's
//!   window and is not importable. Unify onto receipts.rs's
//!   `TransitionJournal` once it compiles.
//!
//! Illegal transitions refuse with typed remediation; tampered evidence
//! refuses before any WorkOrder is proposed; protected paths refuse at
//! proposal time. IO is confined to evidence verification: reading tree
//! bytes to bind each edit's before/after sha256 commitments to the real
//! working tree. Everything else is IO-free.
//!
//! Authority is stamped `NONE` by the imported `admit_work_order`; this
//! bridge never creates authority.

