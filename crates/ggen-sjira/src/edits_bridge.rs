/// A proposed WorkOrder candidate plus the evidence binding that produced it.
#[derive(Debug)]
pub struct ProposedOrder {
    pub work_order: WorkOrder,
    /// Evidence verification the proposal is bound to.
    pub evidence: EvidenceCheck,
}

/// Build the WorkOrder candidate for a verified batch. Blast-radius
/// evidence is attached only when a [`SymbolGraph`] handle is present.
pub fn propose_work_order(
    batch: &EditBatch, ctx: &TreeContext, evidence: EvidenceCheck, graph: Option<&dyn SymbolGraph>,
) -> ProposedOrder {
    let mut required_evidence: Vec<String> = batch
        .edits
        .iter()
        .map(|e| format!("path:{}", e.path))
        .collect();
    let mut radius: BTreeSet<String> = BTreeSet::new();
    if let Some(g) = graph {
        for e in &batch.edits {
            radius.extend(g.blast_radius(&e.path));
        }
    }
    for sym in &radius {
        required_evidence.push(format!("blast-radius:{sym}"));
    }
    let identity = format!("EB-{}", evidence.batch_digest.trim_start_matches("sha256:"));
    let work_order = WorkOrder {
        identity,
        title: batch.description.clone(),
        description: format!(
            "Edit batch over {} path(s): {}",
            batch.edits.len(),
            batch
                .edits
                .iter()
                .map(|e| e.path.as_str())
                .collect::<Vec<_>>()
                .join(", ")
        ),
        subject: batch.edits[0].path.clone(),
        repository: ctx.repository.clone(),
        base_sha: ctx.base_sha.clone(),
        standing: Standing::Unknown,
        evidence_ceiling: "UNVERIFIED".to_string(),
        promotion_rule: "courts".to_string(),
        replay_identity: evidence.batch_digest.clone(),
        origin_authority: format!("bridge://edits/{}", ctx.repository),
        projections: vec!["jira".to_string()],
        required_courts: vec!["admission".to_string()],
        required_evidence,
        acceptance: vec![batch.verification_command.clone()],
        falsifiers: vec![batch.mutation_description.clone()],
    };
    ProposedOrder {
        work_order,
        evidence,
    }
}

