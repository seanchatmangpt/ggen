//! textDocument/moniker for ggen-generated symbols (reverse-80/20 §2).
//!
//! A ggen moniker is `ggen:<crate>:<symbol-path>`, e.g.
//! `ggen:ggen-cli:generated_commands::COMMANDS`. Deterministic and stable
//! across regenerations: the symbol path is derived from the file's own
//! declaration structure (module/enum scope stack + identifier), never from
//! byte offsets, so the same ontology regenerating the same surface yields the
//! same moniker.
//!
//! Implementation note (disclosure): ggen-lsp has no tree-sitter and no regex
//! dependency, and this lane owns only this file, so resolution uses one
//! deterministic line-based scanner that tracks `mod`/`enum` block nesting by
//! brace counting. There is exactly one resolution algorithm for every input —
//! no silent fallback switching.

use lsp_max::lsp_types::{Position, Range};
use std::fmt;
use std::path::{Path, PathBuf};

/// Banner fragments identifying a ggen-generated file.
///
/// Both spellings seen in the wild are accepted: the long form used by
/// templates (`Code generated by ggen`) and the form already present in this
/// crate's analyzers (`Auto-generated by ggen`).
pub const GGEN_BANNER_MARKERS: [&str; 2] = ["Code generated by ggen", "Auto-generated by ggen"];

/// How many leading lines to scan for the generated banner.
pub const BANNER_SCAN_LINES: usize = 10;

/// Does this source text carry the ggen generated-file banner?
pub fn is_generated_file(source: &str) -> bool {
    source
        .lines()
        .take(BANNER_SCAN_LINES)
        .any(|l| GGEN_BANNER_MARKERS.iter().any(|m| l.contains(m)))
}

/// A ggen moniker: crate identity + `::`-separated symbol path.
#[derive(Debug, Clone, PartialEq, Eq, Hash)]
pub struct Moniker {
    /// Crate identity segment, e.g. `ggen-cli`, `abb-sbb`.
    pub crate_name: String,
    /// Symbol path segments, e.g. `["generated_commands", "COMMANDS"]`.
    pub symbol_path: Vec<String>,
}

impl fmt::Display for Moniker {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(
            f,
            "ggen:{}:{}",
            self.crate_name,
            self.symbol_path.join("::")
        )
    }
}

impl Moniker {
    pub fn new(crate_name: impl Into<String>, symbol_path: Vec<String>) -> Self {
        Moniker {
            crate_name: crate_name.into(),
            symbol_path,
        }
    }

    /// Parse `ggen:<crate>:<a::b::c>`.
    pub fn parse(s: &str) -> Option<Moniker> {
        let rest = s.strip_prefix("ggen:")?;
        let (crate_name, path) = rest.split_once(':')?;
        if crate_name.is_empty() || path.is_empty() {
            return None;
        }
        let symbol_path: Vec<String> = path.split("::").map(str::to_string).collect();
        if symbol_path.iter().any(String::is_empty) {
            return None;
        }
        Some(Moniker {
            crate_name: crate_name.to_string(),
            symbol_path,
        })
    }
}

/// If this line opens a named `mod` or `enum` scope, its name.
fn declared_scope(line: &str) -> Option<String> {
    let line = line.trim();
    // `pub mod X {`, `mod X {`, `pub enum E {`, `enum E {` — brace on the same
    // line (generated Rust convention; kernel lib.rs qualifies).
    let after_mod = line
        .strip_prefix("pub mod ")
        .or_else(|| line.strip_prefix("mod "))
        .or_else(|| line.strip_prefix("pub enum "))
        .or_else(|| line.strip_prefix("enum "));
    let name = after_mod?;
    let name = name.split(&['{', ':', ';', ' '][..]).next()?;
    let name = name.trim();
    if name.is_empty() || !line.contains('{') {
        return None;
    }
    Some(name.to_string())
}

/// Net brace delta on a line, honoring string/char literals and line comments.
fn brace_delta(line: &str) -> isize {
    let mut in_str = false;
    let mut in_char = false;
    let mut escaped = false;
    let mut delta = 0isize;
    let mut chars = line.chars();
    while let Some(c) = chars.next() {
        if escaped {
            escaped = false;
            continue;
        }
        match c {
            '\\' if in_str || in_char => escaped = true,
            '"' if !in_char => in_str = !in_str,
            '\'' if !in_str => in_char = !in_char,
            '{' if !in_str && !in_char => delta += 1,
            '}' if !in_str && !in_char => delta -= 1,
            '/' if !in_str && !in_char && chars.next() == Some('/') => {
                // Line comment: ignore the rest of the line.
                break;
            }
            _ => {}
        }
    }
    delta
}

/// The identifier (word) overlapping a 0-based (line, character) offset.
pub fn identifier_at_position(source: &str, line: u32, character: u32) -> Option<String> {
    let line_text = source.lines().nth(line as usize)?;
    let bytes = line_text.as_bytes();
    let pos = character as usize;
    if pos > bytes.len() {
        return None;
    }
    let is_word = |c: u8| c.is_ascii_alphanumeric() || c == b'_';
    // Cursor must sit on or immediately after a word char.
    if (pos == 0 || !is_word(bytes[pos - 1])) && (pos >= bytes.len() || !is_word(bytes[pos])) {
        return None;
    }
    let mut start = pos;
    while start > 0 && is_word(bytes[start - 1]) {
        start -= 1;
    }
    let mut end = pos.min(bytes.len());
    while end < bytes.len() && is_word(bytes[end]) {
        end += 1;
    }
    if start == end {
        None
    } else {
        Some(line_text[start..end].to_string())
    }
}

/// Scanner state while walking a file line-by-line: open `mod`/`enum` blocks.
#[derive(Debug, Default)]
struct ScopeStack {
    segments: Vec<String>,
    /// Total brace depth at which each open scope closes (exclusive bound).
    close_depth: Vec<isize>,
    depth: isize,
}

impl ScopeStack {
    fn step(&mut self, line: &str) {
        if let Some(name) = declared_scope(line) {
            let delta = brace_delta(line);
            self.close_depth.push(self.depth + delta);
            self.segments.push(name);
        }
        self.depth += brace_delta(line);
        self.sync();
    }

    fn sync(&mut self) {
        while let Some(&cd) = self.close_depth.last() {
            if self.depth < cd {
                self.close_depth.pop();
                self.segments.pop();
            } else {
                break;
            }
        }
    }

    fn path(&self) -> Vec<String> {
        self.segments.clone()
    }
}

/// The ggen moniker for the symbol under a cursor position.
///
/// `crate_name` is the identity segment of the produced moniker
/// (`ggen:<crate>:...`); the symbol path is the enclosing module/enum path
/// plus the identifier under the cursor. Returns `None` off-symbol or outside
/// a ggen-generated file.
pub fn moniker_at_position(
    crate_name: &str, source: &str, line: u32, character: u32,
) -> Option<Moniker> {
    if !is_generated_file(source) {
        return None;
    }
    let ident = identifier_at_position(source, line, character)?;
    let mut stack = ScopeStack::default();
    for text in source.lines().take(line as usize) {
        stack.step(text);
    }
    let mut path = stack.path();
    if path.last().map(|s| s == &ident).unwrap_or(false) {
        // Cursor is on the scope's own declaration name; the moniker is the
        // scope itself.
        return Some(Moniker::new(crate_name, path));
    }
    path.push(ident);
    Some(Moniker::new(crate_name, path))
}

/// A resolved moniker hit: file + range.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct MonikerHit {
    pub file: PathBuf,
    pub range: Range,
}

/// Resolve a moniker against one source text: the first occurrence of the
/// leaf identifier on a line whose enclosing scope path equals the moniker's
/// parent path.
///
/// Also resolves top-level items (`path == []`): any line at brace depth 0
/// containing the leaf as a standalone word.
pub fn resolve_moniker_in_source(m: &Moniker, source: &str) -> Option<Range> {
    let leaf = m.symbol_path.last()?.clone();
    let parent = &m.symbol_path[..m.symbol_path.len() - 1];
    let mut stack = ScopeStack::default();
    for (idx, text) in source.lines().enumerate() {
        let path_before = stack.path();
        let on_target_line = path_before == parent;
        stack.step(text);
        if on_target_line {
            for (col, w) in words_on_line(text) {
                if w == leaf {
                    return Some(Range {
                        start: Position {
                            line: idx as u32,
                            character: col as u32,
                        },
                        end: Position {
                            line: idx as u32,
                            character: col as u32 + leaf.chars().count() as u32,
                        },
                    });
                }
            }
        }
    }
    None
}

/// Standalone words on a line, with their byte-column start offsets.
fn words_on_line(text: &str) -> Vec<(usize, String)> {
    let bytes = text.as_bytes();
    let is_word = |c: u8| c.is_ascii_alphanumeric() || c == b'_';
    let mut out = Vec::new();
    let mut i = 0;
    while i < bytes.len() {
        if is_word(bytes[i]) && (i == 0 || !is_word(bytes[i - 1])) {
            let start = i;
            while i < bytes.len() && is_word(bytes[i]) {
                i += 1;
            }
            out.push((start, text[start..i].to_string()));
        } else {
            i += 1;
        }
    }
    out
}

/// Resolve a moniker by scanning a tree of generated surfaces.
///
/// Only banner-bearing `.rs` files participate. Returns every matching hit;
/// the same symbol can legitimately appear in more than one generated surface,
/// so all hits are returned (deterministic order: file path, then position).
pub fn resolve_moniker_in_tree(m: &Moniker, root: &Path) -> Vec<MonikerHit> {
    let mut hits = Vec::new();
    for entry in walkdir::WalkDir::new(root)
        .into_iter()
        .filter_map(Result::ok)
        .filter(|e| e.file_type().is_file())
    {
        let path = entry.path();
        if path.extension().map(|e| e != "rs").unwrap_or(true) {
            continue;
        }
        let Ok(source) = std::fs::read_to_string(path) else {
            continue;
        };
        if !is_generated_file(&source) {
            continue;
        }
        if let Some(range) = resolve_moniker_in_source(m, &source) {
            hits.push(MonikerHit {
                file: path.to_path_buf(),
                range,
            });
        }
    }
    hits.sort_by(|a, b| {
        (&a.file, a.range.start.line, a.range.start.character).cmp(&(
            &b.file,
            b.range.start.line,
            b.range.start.character,
        ))
    });
    hits
}

/// Kernel-surface monikers: `ggen:abb-sbb:Refusal::SBB_MUTABLE`-style ids.
///
/// The kernel file is not banner-generated, so this bypasses the
/// generated-file gate and resolves a two-segment `<Enum>::<Variant>` path
/// directly against the kernel source (e.g.
/// `crates/ggen-abb-sbb/src/lib.rs`).
pub fn resolve_kernel_moniker(m: &Moniker, kernel_source: &str) -> Option<Range> {
    if m.symbol_path.len() != 2 {
        return None;
    }
    let (enum_name, variant) = (m.symbol_path[0].as_str(), m.symbol_path[1].as_str());
    let mut inside_enum = false;
    for (idx, text) in kernel_source.lines().enumerate() {
        if !inside_enum {
            let trimmed = text.trim();
            let is_decl = (trimmed.starts_with("pub enum ") || trimmed.starts_with("enum "))
                && trimmed.contains(enum_name)
                && trimmed.contains('{');
            if is_decl {
                inside_enum = true;
            }
            continue;
        }
        // Inside the enum body: match a standalone variant-name word, or the
        // variant's SCREAMING_SNAKE code in its `#[error("CODE: ...")]`
        // attribute — the kernel names variants `SbbMutable` but publishes the
        // wire/code identity `SBB_MUTABLE` through the error attribute, and
        // the moniker surface uses the code.
        for (col, w) in words_on_line(text) {
            let is_attr_code = text.trim_start().starts_with("#[error(") && w == variant;
            if w == variant || is_attr_code {
                let width = variant.chars().count() as u32;
                return Some(Range {
                    start: Position {
                        line: idx as u32,
                        character: col as u32,
                    },
                    end: Position {
                        line: idx as u32,
                        character: col as u32 + width,
                    },
                });
            }
        }
        let _ = &text;
    }
    None
}
