//! Regeneration-hygiene diagnostic rules (GGEN-DIAG-NNN family).
//!
//! Self-contained by construction: this module takes no `crate::` paths so it
//! can be compiled both as a `ggen-lsp` library module (wiring into `lib.rs`
//! is a one-line follow-up) and directly into the integration test via
//! `#[path]` include. The trio implemented here comes from the r80-12 dispatch;
//! `DIAGNOSTIC_RULES_TODO.md`'s own rows (GGEN-SRC-004 implemented,
//! GGEN-SPARQL-VAR-001 / GGEN-TEMPLATE-CONTEXT-001 subsumed by GGEN-TPL-001)
//! need no new code.
//!
//! Position model: line-based, not tree-sitter. R80-1 did not land a
//! tree-sitter parse dependency in this crate (no `tree-sitter`/`tree_sitter`
//! entry in `crates/ggen-lsp/Cargo.toml`), so spans are computed by line/column
//! scan over `(uri, text)`.
//!
//! Rules:
//! - `GGEN-DIAG-001` stale-banner / regeneration pending: a generated file
//!   whose ontology source (named in its ggen provenance banner) has a newer
//!   mtime than the file itself.
//! - `GGEN-DIAG-002` unrendered-template residue: `{{` reaching a
//!   non-template file means a Tera expression failed to render.
//! - `GGEN-DIAG-003` moniker-unstable: a file the ontology (ggen.toml
//!   generation rules) declares as generated carries no ggen provenance
//!   banner.

use std::collections::BTreeSet;
use std::path::Path;

use lsp_max::lsp_types_max::{Diagnostic, DiagnosticSeverity, NumberOrString, Position, Range};

/// GGEN-DIAG-001: ontology source is newer than the generated file it produced.
pub const GGEN_DIAG_001: &str = "GGEN-DIAG-001";

/// GGEN-DIAG-002: unrendered Tera residue (`{{ ... }}`) in a non-template file.
pub const GGEN_DIAG_002: &str = "GGEN-DIAG-002";

/// GGEN-DIAG-003: ontology-declared generated file missing its ggen banner.
pub const GGEN_DIAG_003: &str = "GGEN-DIAG-003";

/// Marker every `ggen sync` provenance banner carries.
pub const BANNER_MARKER: &str = "GENERATED by";

/// ggen's banner names its ontology source as `... from `<path>` ...`.
const BANNER_FROM_TOKEN: &str = "from `";

/// File extensions that are Tera templates (where `{{` is expected, not residue).
const TEMPLATE_EXTENSIONS: &[&str] = &["tera", "j2", "jinja", "jinja2", "tmpl"];

/// Severity for each rule, as `lsp_types` severity values.
const SEVERITY_REGENERATION_PENDING: DiagnosticSeverity = DiagnosticSeverity::WARNING;
const SEVERITY_RESIDUE: DiagnosticSeverity = DiagnosticSeverity::ERROR;
const SEVERITY_MONIKER: DiagnosticSeverity = DiagnosticSeverity::ERROR;

/// One rule in the registry: a named check over a `(uri, text)` surface.
pub struct DiagnosticRule {
    pub code: &'static str,
    pub severity: DiagnosticSeverity,
    pub description: &'static str,
}

/// The implemented rule set, in code order.
pub const DIAGNOSTIC_RULES: &[DiagnosticRule] = &[
    DiagnosticRule {
        code: GGEN_DIAG_001,
        severity: SEVERITY_REGENERATION_PENDING,
        description:
            "ontology source mtime is newer than the generated file (regeneration pending)",
    },
    DiagnosticRule {
        code: GGEN_DIAG_002,
        severity: SEVERITY_RESIDUE,
        description: "unrendered Tera residue (`{{`) in a non-template file",
    },
    DiagnosticRule {
        code: GGEN_DIAG_003,
        severity: SEVERITY_MONIKER,
        description: "ontology-declared generated file carries no ggen provenance banner",
    },
];

/// Local span builder mirroring `analyzers::diag::at` (kept local so this
/// module has no `crate::` dependency and can be test-compiled via `#[path]`).
#[must_use]
fn at(
    start_line: u32, start_col: u32, end_line: u32, end_col: u32, severity: DiagnosticSeverity,
    code: Option<&str>, message: impl Into<String>,
) -> Diagnostic {
    Diagnostic {
        range: Range {
            start: Position {
                line: start_line,
                character: start_col,
            },
            end: Position {
                line: end_line,
                character: end_col,
            },
        },
        severity: Some(severity),
        code: code.map(|c| NumberOrString::String(c.to_string())),
        code_description: None,
        source: Some("ggen-lsp".to_string()),
        message: message.into(),
        related_information: None,
        tags: None,
        data: Some(serde_json::json!({"source_id": "ggen_lsp_observer"})),
    }
}

/// Extract the ontology source path a ggen provenance banner names, if any.
///
/// Recognizes ggen's real banner shape: `... GENERATED by `ggen sync run` from
/// `<ontology-path>` ...` — the path is the first backtick-quoted segment after
/// the `from ` token on the banner line.
#[must_use]
pub fn provenance_banner_source_path(text: &str) -> Option<&str> {
    for line in text.lines() {
        if !line.contains(BANNER_MARKER) {
            continue;
        }
        let idx = line.find(BANNER_FROM_TOKEN)?;
        let rest = &line[idx + BANNER_FROM_TOKEN.len()..];
        let end = rest.find('`')?;
        if end > 0 {
            return Some(&rest[..end]);
        }
    }
    None
}

/// 0-based line number of the provenance banner, if present.
#[must_use]
fn banner_line(text: &str) -> Option<u32> {
    text.lines()
        .position(|l| l.contains(BANNER_MARKER))
        .and_then(|i| u32::try_from(i).ok())
}

/// Whether `uri` names a Tera template file (where `{{` is legitimate syntax).
#[must_use]
fn is_template_uri(uri: &str) -> bool {
    let lower = uri.to_ascii_lowercase();
    TEMPLATE_EXTENSIONS
        .iter()
        .any(|ext| lower.ends_with(&format!(".{ext}")))
        || lower.contains("/templates/")
}

/// Byte offset of the first `{{` at or after `from` in `s`, as (line, col) in
/// the original document when `line_starts` maps document lines to offsets.
#[must_use]
fn find_residue_span(text: &str) -> impl Iterator<Item = (u32, u32, u32, u32)> + '_ {
    let mut spans = Vec::new();
    for (i, line) in (0_u32..).zip(text.lines()) {
        let line_idx = i;
        let mut search_from = 0usize;
        while let Some(rel) = line[search_from..].find("{{") {
            let col = {
                // Byte offset -> approximate character column (UTF-8 aware:
                // count chars up to the match, matching LSP UTF-16 closely
                // enough for ASCII-prefix templates).
                let byte_col = search_from + rel;
                line[..byte_col].chars().count()
            };
            let end_col = {
                let end_byte = (search_from + rel + 2).min(line.len());
                line[..end_byte].chars().count()
            };
            spans.push((
                line_idx,
                u32::try_from(col).unwrap_or(0),
                line_idx,
                u32::try_from(end_col).unwrap_or(0),
            ));
            search_from = search_from + rel + 2;
        }
    }
    spans.into_iter()
}

/// GGEN-DIAG-002: unrendered Tera residue in a non-template file.
///
/// Every `{{ ... }}`-style opening in a file whose URI does not name a
/// template surface means the renderer emitted an expression instead of a
/// value — a real defect in the generated artifact, not template source.
/// Returns one ERROR per occurrence, positioned at the `{{`.
#[must_use]
pub fn unrendered_residue_diagnostics(uri: &str, text: &str) -> Vec<Diagnostic> {
    if is_template_uri(uri) {
        return Vec::new();
    }
    find_residue_span(text)
        .map(|(sl, sc, el, ec)| {
            at(
                sl,
                sc,
                el,
                ec,
                SEVERITY_RESIDUE,
                Some(GGEN_DIAG_002),
                format!(
                    "GGEN-DIAG-002 UNRENDERED_TEMPLATE_RESIDUE: `{{` reached `{uri}` at line \
                     {}. Template expressions must render before `ggen sync` writes the file — \
                     check the rule's template projections and the SELECT variables that feed \
                     them, then regenerate with `ggen sync run`.",
                    sl + 1
                ),
            )
        })
        .collect()
}

/// GGEN-DIAG-001: regeneration pending.
///
/// A file carrying a ggen provenance banner is stale when the ontology source
/// named in that banner has a modification time strictly newer than the
/// generated file itself. Pure-text variant `stale_banner_diagnostics` fires
/// on banner-shape problems; this variant stats both files.
///
/// `uri` is the on-disk generated file; its text (as in the editor buffer) is
/// `text`. Returns a WARNING positioned on the banner line.
#[must_use]
pub fn stale_regeneration_diagnostics(uri: &str, text: &str) -> Vec<Diagnostic> {
    let Some(source_path) = provenance_banner_source_path(text) else {
        return Vec::new();
    };
    let file_path = uri.strip_prefix("file://").unwrap_or(uri);
    let Ok(source_meta) = Path::new(source_path).metadata() else {
        // Source missing/unstatable: the stale check is vacuous here by
        // design — GGEN-RULE-001 already owns missing-binding detection.
        return Vec::new();
    };
    let Ok(file_meta) = Path::new(file_path).metadata() else {
        return Vec::new();
    };
    let (Ok(src_mtime), Ok(file_mtime)) = (source_meta.modified(), file_meta.modified()) else {
        return Vec::new();
    };
    if src_mtime <= file_mtime {
        return Vec::new();
    }
    let line = banner_line(text).unwrap_or(0);
    vec![at(
        line,
        0,
        line,
        u32::MAX,
        SEVERITY_REGENERATION_PENDING,
        Some(GGEN_DIAG_001),
        format!(
            "GGEN-DIAG-001 STALE_BANNER_REGENERATION_PENDING: ontology source `{source_path}` \
             is newer than `{file_path}` — this file was generated from an older graph and is \
             one `ggen sync run` behind. Regenerate with `ggen sync run` to clear."
        ),
    )]
}

/// GGEN-DIAG-003: moniker-unstable files.
///
/// `declared_generated` is the set of files the ontology's generation rules
/// declare as generated outputs (paths as they appear in `ggen.toml`, e.g.
/// `src/generated_contract.rs`, resolved against the same prefix rules as
/// `uri`). A declared file whose text carries no ggen provenance banner has an
/// unstable moniker: consumers cannot tell generated source from hand-written
/// source, and the next `ggen sync run` may clobber edits silently.
///
/// Returns one ERROR per declared file that lacks the banner (here: at most
/// one, for the single `(uri, text)` surface under check).
#[must_use]
pub fn moniker_diagnostics(
    uri: &str, text: &str, declared_generated: &BTreeSet<String>,
) -> Vec<Diagnostic> {
    let file_path = uri.strip_prefix("file://").unwrap_or(uri);
    let declared = declared_generated
        .iter()
        .any(|decl| paths_equivalent(file_path, decl));
    if !declared {
        return Vec::new();
    }
    if text.contains(BANNER_MARKER) {
        return Vec::new();
    }
    vec![at(
        0,
        0,
        0,
        0,
        SEVERITY_MONIKER,
        Some(GGEN_DIAG_003),
        format!(
            "GGEN-DIAG-003 MONIKER_UNSTABLE: `{file_path}` is declared as a generation-rule \
             output but carries no ggen provenance banner. Add the file to the declaring \
             rule's template banner (regenerate with `ggen sync run`) so provenance is \
             machine-checkable, or remove it from the rule if it is hand-written source."
        ),
    )]
}

/// Path equivalence for declaration matching: equal after normalization, or
/// equal on the last `n` components where `n` is the shorter path's depth
/// (so a manifest-relative `src/generated_contract.rs` matches an absolute
/// `/repo/crates/x/src/generated_contract.rs`).
#[must_use]
fn paths_equivalent(a: &str, b: &str) -> bool {
    if a == b {
        return true;
    }
    let pa: Vec<_> = Path::new(a).components().collect();
    let pb: Vec<_> = Path::new(b).components().collect();
    let n = pa.len().min(pb.len());
    n > 0 && pa[pa.len() - n..] == pb[pb.len() - n..]
}

/// Run every rule over one surface, with the ontology's declared-generated set.
#[must_use]
pub fn run_rules(uri: &str, text: &str, declared_generated: &BTreeSet<String>) -> Vec<Diagnostic> {
    let mut out = stale_regeneration_diagnostics(uri, text);
    out.extend(unrendered_residue_diagnostics(uri, text));
    out.extend(moniker_diagnostics(uri, text, declared_generated));
    out
}

#[cfg(test)]
mod inline_tests {
    use super::*;

    #[test]
    fn banner_source_path_extracts_real_ggen_banner_shape() {
        let banner = "//! GENERATED by `ggen sync run` from `.specify/repo-facts.ttl` \
                      (`rf:DiagnosticCode` individuals), rule `gen-diag-codes-rust`.";
        assert_eq!(
            provenance_banner_source_path(banner),
            Some(".specify/repo-facts.ttl")
        );
    }

    #[test]
    fn banner_source_path_absent_without_banner() {
        assert_eq!(provenance_banner_source_path("pub fn f() {}"), None);
    }
}
