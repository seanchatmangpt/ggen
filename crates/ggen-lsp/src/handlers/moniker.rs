//! `textDocument/moniker` handler — R80-2 `moniker::moniker_at_position`
//! (brace-counting scope scanner) over open buffers of generated surfaces,
//! plus the shared cursor-to-moniker core and the G4 fallback resolution used
//! by definition/references.

use crate::server::GgenLanguageServer;
use lsp_max::jsonrpc::Result;
use lsp_max::lsp_types_max::{
    Moniker as LspMoniker, MonikerKind, Position, Range, UniquenessLevel, Url,
};

/// A resolved fallback hit ready to surface as an LSP `Location`.
#[derive(Debug, Clone, PartialEq, Eq)]
pub(crate) struct FallbackHit {
    pub uri: Url,
    pub range: Range,
}

/// `textDocument/moniker`: resolve the symbol under the cursor to a
/// `ggen:<crate>:<symbol path>` moniker. Fires on surfaces that carry a ggen
/// provenance banner (`moniker::is_generated_file`) OR that the ontology's
/// generation rules declare as outputs (`TokensEngine::is_generated_uri`).
pub async fn handle(
    server: &GgenLanguageServer, params: lsp_max::lsp_types_max::MonikerParams,
) -> Result<Option<Vec<lsp_max::lsp_types_max::Moniker>>> {
    let uri = &params.text_document_position_params.text_document.uri;
    let position = &params.text_document_position_params.position;
    moniker_for_cursor(server, uri, position).await
}

/// Shared cursor-to-moniker core (G4): the banner-or-ontology-declared gate
/// plus the brace-counting scope scan, shared by `textDocument/moniker` and
/// the definition/references fallback (one moniker calculus, many bindings).
pub(crate) async fn moniker_for_cursor(
    server: &GgenLanguageServer, uri: &Url, position: &Position,
) -> Result<Option<Vec<LspMoniker>>> {
    let Some(content) = server.state.get_document(uri).await else {
        return Ok(None);
    };
    let banner_generated = crate::moniker::is_generated_file(&content);
    let declared = server
        .tokens_engine
        .lock()
        .await
        .is_generated_uri(uri.as_str());
    if !(banner_generated || declared) {
        return Ok(None);
    }
    // `moniker_at_position` banner-gates internally (R80-2 law: monikers are
    // a generated-file surface). For ontology-DECLARED generated files whose
    // banner spelling differs (generated_commands.rs says "generated by root
    // ggen.toml rule"), prepend a marker line so the same scanner applies;
    // the cursor line shifts by 1 and the returned Moniker carries no
    // positions, so resolution is unaffected. Disclosed in the E80-05 receipt.
    let (scan_text, scan_line) = if banner_generated {
        (content, position.line)
    } else {
        (
            format!("// {}\n{}", crate::moniker::GGEN_BANNER_MARKERS[0], content),
            position.line + 1,
        )
    };
    let crate_name = crate_name_from_uri(uri.as_str());
    let Some(moniker) =
        crate::moniker::moniker_at_position(&crate_name, &scan_text, scan_line, position.character)
    else {
        return Ok(None);
    };
    Ok(Some(vec![LspMoniker {
        scheme: "ggen".to_string(),
        identifier: moniker.to_string(),
        unique: UniquenessLevel::Project,
        kind: Some(MonikerKind::Export),
    }]))
}

/// G4 fallback: resolve the cursor moniker against the project root that
/// CONTAINS the file (`ServerState::project_root_for` ggen.toml walk-up, not
/// the workspace root). Two-segment Enum::Variant monikers resolve via
/// `resolve_kernel_moniker` against `crates/ggen-abb-sbb/src/lib.rs` under
/// that root; everything else resolves by scanning banner-bearing generated
/// surfaces in the tree (`resolve_moniker_in_tree`), returning ALL hits.
///
/// Strictly behind analyzer None/empty in definition/references.
pub(crate) async fn moniker_fallback_hits(
    server: &GgenLanguageServer, uri: &Url, position: &Position,
) -> Vec<FallbackHit> {
    let Ok(Some(monikers)) = moniker_for_cursor(server, uri, position).await else {
        return Vec::new();
    };
    let Some(root) = server.state.project_root_for(uri) else {
        return Vec::new();
    };

    let mut hits: Vec<FallbackHit> = Vec::new();
    for wire_moniker in monikers {
        let Some(m) = crate::moniker::Moniker::parse(&wire_moniker.identifier) else {
            continue;
        };
        if m.symbol_path.len() == 2 {
            // Kernel shape: Enum::Variant against the abb-sbb kernel lib.rs
            // under the project root containing the file. Kernel-first: when
            // the kernel file is absent or the variant misses, the same
            // moniker falls through to the banner-bearing tree scan below
            // (module::SYMBOL monikers are also 2-segment).
            let kernel_path = root.join("crates/ggen-abb-sbb/src/lib.rs");
            if let Some(source) = std::fs::read_to_string(&kernel_path).ok() {
                if let Some(range) = crate::moniker::resolve_kernel_moniker(&m, &source) {
                    if let Some(hit_uri) = wire_url_from_path(&kernel_path) {
                        hits.push(FallbackHit {
                            uri: hit_uri,
                            range,
                        });
                        continue;
                    }
                }
            }
        }
        {
            for hit in crate::moniker::resolve_moniker_in_tree(&m, &root) {
                if let Some(hit_uri) = wire_url_from_path(&hit.file) {
                    hits.push(FallbackHit {
                        uri: hit_uri,
                        range: hit.range,
                    });
                }
            }
        }
    }
    hits
}

/// Wire-Url construction for file paths: the wire `Url`/`DocumentUri` type is
/// a string-backed newtype parsed from the url-crate serialization (same
/// pattern as `server.rs::url_from_path`).
fn wire_url_from_path(path: &std::path::Path) -> Option<Url> {
    let text = url::Url::from_file_path(path).ok()?.to_string();
    text.parse().ok()
}

/// Crate identity segment: the path component after `crates/`, else the file
/// stem (dashes preserved). Deterministic; matches workspace layout
/// `crates/<crate-name>/src/<file>.rs`.
fn crate_name_from_uri(uri: &str) -> String {
    let path = uri.strip_prefix("file://").unwrap_or(uri);
    let segments: Vec<&str> = path.split('/').filter(|s| !s.is_empty()).collect();
    if let Some(idx) = segments.iter().position(|s| *s == "crates") {
        if let Some(name) = segments.get(idx + 1) {
            return (*name).to_string();
        }
    }
    segments
        .last()
        .map(|s| s.rsplit_once('.').map_or(*s, |(stem, _)| stem))
        .unwrap_or("unknown")
        .to_string()
}
