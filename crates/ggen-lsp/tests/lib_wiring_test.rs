//! lib.rs module-wiring test: proves each lane-delivered module declared in
//! lib.rs is callable through the crate's public API surface.
//! Covers tokens (R80-1), moniker (R80-2), diagnostics_rules (R80-12).

#![allow(
    clippy::unwrap_used,
    clippy::expect_used,
    clippy::panic,
    clippy::similar_names
)]
use ggen_lsp::diagnostics_rules;
use ggen_lsp::moniker;
use ggen_lsp::tokens;
use std::collections::BTreeSet;

// --- tokens (R80-1) ---

#[test]
fn tokens_engine_full_and_delta_are_callable() {
    let ttl = "\n@prefix ggen: <http://ggen.dev/ontology#> .\n";
    let mut engine = tokens::TokensEngine::from_ontology(ttl, None);
    let text = "pub struct S;\n";
    let full = engine.full("file:///a.rs", text);
    assert!(full.result_id.is_some(), "full() mints a result_id");
    let result_id = full.result_id.clone().unwrap();
    let _delta = engine.delta("file:///a.rs", &result_id, "pub struct T;\n");
}

#[test]
fn tokens_encode_decode_round_trip() {
    let legend = tokens::legend_from_facts(false, false);
    let facts = tokens::parse_ontology_facts("", None);
    let toks = tokens::classify_rust("pub enum E { A }\n", &legend, &facts, false);
    let data = tokens::encode(&toks);
    let back = tokens::decode(&data);
    assert_eq!(toks.len(), back.len());
}

// --- moniker (R80-2) ---

#[test]
fn moniker_parse_resolve_round_trip() {
    let m = moniker::Moniker::new("ggen-core", vec!["foo".to_string(), "Bar".to_string()]);
    let s = m.to_string();
    let parsed = moniker::Moniker::parse(&s).expect("parse own to_string");
    assert_eq!(parsed, m);
    assert!(moniker::is_generated_file(
        "// Code generated by ggen
pub fn f() {}
"
    ));
}

// --- diagnostics_rules (R80-12) ---

#[test]
fn diagnostics_rules_families_are_callable() {
    let uri = "file:///out/projected.rs";
    let text = "pub fn f() {}\n";
    let _ = diagnostics_rules::stale_regeneration_diagnostics(uri, text);
    let _ = diagnostics_rules::unrendered_residue_diagnostics(uri, text);
    let _ = diagnostics_rules::provenance_banner_source_path("// ggen:source: a.ttl\n");
    let declared: BTreeSet<String> = BTreeSet::new();
    let all = diagnostics_rules::run_rules(uri, text, &declared);
    assert!(all.is_empty(), "clean surface yields no diagnostics");
}
