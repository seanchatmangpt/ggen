//! Chicago-style tests for the GGEN-DIAG-NNN regeneration-hygiene rules.
//!
//! Real collaborators: real files on disk with real mtimes (`File::set_modified`,
//! no sleeps), real banner text copied from ggen's actual generated-banner
//! shape. Anti-vacuity: for every rule, the dirty fixture fires AND each
//! trigger-condition mutation (banner removed, mtime inverted, template URI,
//! declaration removed, `{{` removed) collapses the diagnostic to zero —
//! removing the rule's trigger makes the paired assertion fail.

// The module is self-contained (no `crate::` paths), so it compiles directly
// into this test binary; wiring `pub mod diagnostics_rules;` into lib.rs is a
// one-line coordinator follow-up outside this lane's file ownership.
#[path = "../src/diagnostics_rules.rs"]
mod diagnostics_rules;

use std::collections::BTreeSet;
use std::fs::File;
use std::time::{Duration, SystemTime};

use diagnostics_rules::{
    moniker_diagnostics, provenance_banner_source_path, run_rules, stale_regeneration_diagnostics,
    unrendered_residue_diagnostics, BANNER_MARKER, GGEN_DIAG_001, GGEN_DIAG_002, GGEN_DIAG_003,
};

/// ggen's real banner shape (copied from crates/ggen-lsp/src/generated_diagnostic_codes.rs).
fn banner(source_path: &str) -> String {
    format!(
        "//! GENERATED by `ggen sync run` from `{source_path}` (`rf:Foo` individuals), \
         rule `gen-foo-rust` in root `ggen.toml`.\n\npub const TABLE: &str = \"x\";\n"
    )
}

fn codes(diags: &[lsp_max::lsp_types_max::Diagnostic]) -> Vec<Option<String>> {
    diags
        .iter()
        .map(|d| match &d.code {
            Some(lsp_max::lsp_types_max::NumberOrString::String(s)) => Some(s.clone()),
            _ => None,
        })
        .collect()
}

fn declared(paths: &[&str]) -> BTreeSet<String> {
    paths.iter().map(|p| (*p).to_string()).collect()
}

// ---------------------------------------------------------------------------
// GGEN-DIAG-001 — stale banner / regeneration pending (real mtimes on disk)
// ---------------------------------------------------------------------------

#[test]
fn diag_001_fires_when_ontology_source_is_newer_than_generated_file() {
    let dir = tempfile::tempdir().unwrap();
    let gen_path = dir.path().join("generated.rs");
    let src_path = dir.path().join("repo-facts.ttl");
    std::fs::write(&gen_path, banner(src_path.to_str().unwrap())).unwrap();
    std::fs::write(&src_path, "ttl content").unwrap();

    let now = SystemTime::now();
    // Generated file rendered 1000s ago; ontology touched now -> stale.
    File::options().write(true).open(&gen_path).unwrap().set_modified(now - Duration::from_secs(1_000)).unwrap();
    File::options().write(true).open(&src_path).unwrap().set_modified(now).unwrap();

    let uri = format!("file://{}", gen_path.display());
    let text = std::fs::read_to_string(&gen_path).unwrap();
    let diags = stale_regeneration_diagnostics(&uri, &text);

    assert_eq!(codes(&diags), vec![Some(GGEN_DIAG_001.to_string())]);
    assert_eq!(diags[0].severity, Some(lsp_max::lsp_types_max::DiagnosticSeverity::WARNING));
    // Remediation text names the regeneration command (house law).
    assert!(diags[0].message.contains("ggen sync run"));
}

#[test]
fn diag_001_silent_when_generated_file_is_current_or_older_source() {
    let dir = tempfile::tempdir().unwrap();
    let gen_path = dir.path().join("generated.rs");
    let src_path = dir.path().join("repo-facts.ttl");
    std::fs::write(&gen_path, banner(src_path.to_str().unwrap())).unwrap();
    std::fs::write(&src_path, "ttl content").unwrap();

    let now = SystemTime::now();
    // Clean: generated AFTER the ontology (regenerated post-edit).
    File::options().write(true).open(&gen_path).unwrap().set_modified(now).unwrap();
    File::options().write(true).open(&src_path).unwrap().set_modified(now - Duration::from_secs(1_000)).unwrap();

    let uri = format!("file://{}", gen_path.display());
    let text = std::fs::read_to_string(&gen_path).unwrap();
    assert!(stale_regeneration_diagnostics(&uri, &text).is_empty());
}

#[test]
fn diag_001_anti_vacuity_banner_removed_collapses_trigger() {
    let dir = tempfile::tempdir().unwrap();
    let gen_path = dir.path().join("generated.rs");
    let src_path = dir.path().join("repo-facts.ttl");
    // Mutation: strip the provenance banner (trigger condition gone).
    std::fs::write(&gen_path, "pub const TABLE: &str = \"x\";\n").unwrap();
    std::fs::write(&src_path, "ttl content").unwrap();

    let now = SystemTime::now();
    File::options().write(true).open(&gen_path).unwrap().set_modified(now - Duration::from_secs(1_000)).unwrap();
    File::options().write(true).open(&src_path).unwrap().set_modified(now).unwrap();

    let uri = format!("file://{}", gen_path.display());
    let text = std::fs::read_to_string(&gen_path).unwrap();
    assert!(stale_regeneration_diagnostics(&uri, &text).is_empty());
}

// ---------------------------------------------------------------------------
// GGEN-DIAG-002 — unrendered Tera residue
// ---------------------------------------------------------------------------

#[test]
fn diag_002_fires_on_unrendered_expression_in_non_template_file() {
    let uri = "file:///repo/crates/x/src/generated_table.rs";
    let text = "pub const NAME: &str = \"{{ project_name }}\";\n";
    let diags = unrendered_residue_diagnostics(uri, text);

    assert_eq!(codes(&diags), vec![Some(GGEN_DIAG_002.to_string())]);
    assert_eq!(diags[0].severity, Some(lsp_max::lsp_types_max::DiagnosticSeverity::ERROR));
    // Position-aware: line 0, columns of the `{{`.
    assert_eq!(diags[0].range.start.line, 0);
    assert_eq!(diags[0].range.start.character, 24);
    assert!(diags[0].message.contains("ggen sync run"));
}

#[test]
fn diag_002_fires_per_occurrence_with_line_positions() {
    let uri = "file:///repo/out.toml";
    let text = "a = \"{{ x }}\"\n\nb = \"{{ y }}\"\n";
    let diags = unrendered_residue_diagnostics(uri, text);
    assert_eq!(diags.len(), 2);
    assert_eq!(diags[0].range.start.line, 0);
    assert_eq!(diags[1].range.start.line, 2);
}

#[test]
fn diag_002_silent_on_template_files_where_double_brace_is_syntax() {
    let uri = "file:///repo/templates/service.rs.tera";
    let text = "name = \"{{ project_name }}\"\n";
    assert!(unrendered_residue_diagnostics(uri, text).is_empty());
}

#[test]
fn diag_002_anti_vacuity_removing_residue_collapses_trigger() {
    // Mutation: render actually happened (`{{` gone) -> rule must go silent.
    let uri = "file:///repo/crates/x/src/generated_table.rs";
    assert!(unrendered_residue_diagnostics(uri, "pub const NAME: &str = \"acme\";\n").is_empty());
}

