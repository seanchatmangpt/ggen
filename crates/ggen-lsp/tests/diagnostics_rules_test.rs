#[test]
fn run_rules_aggregates_all_three_families_on_one_dirty_surface() {
    let dir = tempfile::tempdir().unwrap();
    let gen_path = dir.path().join("generated.rs");
    let src_path = dir.path().join("repo-facts.ttl");
    // Dirty on 001 (stale) + 002 (residue) + 003 (declared but banner present
    // here, so only 001+002 fire; the banner exists so 003 stays silent --
    // 003's firing case has its own test above).
    std::fs::write(&gen_path, banner(src_path.to_str().unwrap())).unwrap();
    std::fs::write(
        &gen_path,
        format!(
            "{}\npub const NAME: &str = \"{{{{ unclosed }}}}\";\n",
            banner(src_path.to_str().unwrap())
        ),
    )
    .unwrap();
    std::fs::write(&src_path, "ttl").unwrap();

    let now = SystemTime::now();
    File::options().write(true).open(&gen_path).unwrap().set_modified(now - Duration::from_secs(500)).unwrap();
    File::options().write(true).open(&src_path).unwrap().set_modified(now).unwrap();

    let uri = format!("file://{}", gen_path.display());
    let text = std::fs::read_to_string(&gen_path).unwrap();
    let decl = declared(&[gen_path.to_str().unwrap()]);
    let all = run_rules(&uri, &text, &decl);

    let got = codes(&all);
    assert!(got.contains(&Some(GGEN_DIAG_001.to_string())), "got {got:?}");
    assert!(got.contains(&Some(GGEN_DIAG_002.to_string())), "got {got:?}");
    assert!(!got.contains(&Some(GGEN_DIAG_003.to_string())), "banner present, 003 must stay silent: {got:?}");
}
