// GGEN-DIAG-003 — moniker-unstable (declared generated, banner missing)
// ---------------------------------------------------------------------------

#[test]
fn diag_003_fires_when_declared_file_lacks_provenance_banner() {
    let declared = declared(&["src/generated_contract.rs"]);
    let uri = "file:///repo/crates/x/src/generated_contract.rs";
    let text = "// hand-written-looking source with no banner\npub struct S;\n";
    let diags = moniker_diagnostics(uri, text, &declared);

    assert_eq!(codes(&diags), vec![Some(GGEN_DIAG_003.to_string())]);
    assert_eq!(diags[0].severity, Some(lsp_max::lsp_types_max::DiagnosticSeverity::ERROR));
    assert!(diags[0].message.contains("ggen sync run"));
}

#[test]
fn diag_003_silent_when_banner_present() {
    let declared = declared(&["src/generated_contract.rs"]);
    let uri = "file:///repo/crates/x/src/generated_contract.rs";
    let text = format!("//! {} `ggen sync run` from `o.ttl`...\npub struct S;\n", BANNER_MARKER);
    assert!(moniker_diagnostics(uri, &text, &declared).is_empty());
}

#[test]
fn diag_003_silent_for_files_the_ontology_does_not_declare() {
    // Mutation: declaration removed -> trigger condition gone -> no diagnostic.
    let declared = declared(&["src/other.rs"]);
    let uri = "file:///repo/crates/x/src/generated_contract.rs";
    let text = "pub struct S;\n";
    assert!(moniker_diagnostics(uri, text, &declared).is_empty());
}

#[test]
fn diag_003_suffix_path_matching_resolves_manifest_relative_declarations() {
    // Manifest-relative declaration matches the absolute on-disk URI.
    let declared = declared(&["generated_contract.rs"]);
    let uri = "file:///repo/crates/x/src/generated_contract.rs";
    assert!(!moniker_diagnostics(uri, "pub struct S;\n", &declared).is_empty());
}

