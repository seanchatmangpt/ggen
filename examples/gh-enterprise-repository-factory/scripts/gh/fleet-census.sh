#!/usr/bin/env bash
set -euo pipefail
# fleet-census.sh — STRICTLY READ-ONLY fleet observation (Phase 1).
# Every gh call below is a plain GET (no method-override flags anywhere;
# the tier-1 test asserts the absence of mutating method flags in this file).
# Output TTL carries obs: individuals: OBSERVATION, NOT DESIRED STATE.
# Usage: fleet-census.sh --ttl-out <file> --md-out <file>
ttl_out="" ; md_out=""
while [ $# -gt 0 ]; do
  case "$1" in
    --ttl-out) ttl_out="$2"; shift 2 ;;
    --md-out) md_out="$2"; shift 2 ;;
    *) echo "unknown arg: $1" >&2; exit 2 ;;
  esac
done
if [ -z "$ttl_out" ] || [ -z "$md_out" ]; then
  echo "usage: fleet-census.sh --ttl-out <file> --md-out <file>" >&2
  exit 2
fi
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
gh api --paginate user/repos --jq '.[] | [.full_name, .name, .visibility, (.archived|tostring), (.default_branch // "unknown"), (.has_issues|tostring), (.has_wiki|tostring), (.has_projects|tostring), (.delete_branch_on_merge // false | tostring), (.pushed_at // "unknown")] | join("|")' > "$tmp/repos.txt"
now=$(date -u +%Y-%m-%dT%H:%M:%SZ)
{
  echo "# GENERATED OBSERVATION FACTS — scripts/gh/fleet-census.sh — $now"
  echo "# OBSERVATION, NOT DESIRED STATE. obs: individuals record what the"
  echo "# GitHub API returned at census time. They are NOT ghtf: desired-state"
  echo "# instances and must never be promoted to desired state mechanically."
  echo "@prefix obs: <http://seanchatmangpt.github.io/packs/gh-terraform#obs-> ."
  echo "@prefix xsd: <http://www.w3.org/2001/XMLSchema#> ."
  echo
} > "$ttl_out"
{
  echo "# Fleet Census (Phase 1 — read-only observation)"
  echo
  echo "Generated by scripts/gh/fleet-census.sh at $now."
  echo "OBSERVATION, NOT DESIRED STATE — this table records what the GitHub"
  echo "API returned; it assigns no tiers and creates no desired-state facts."
  echo
  echo "| repo | visibility | archived | default | protection | labels | issues | wiki | projects | del-on-merge | pushed_at | class |"
  echo "|------|-----------|----------|---------|------------|--------|--------|------|----------|--------------|-----------|-------|"
} > "$md_out"
total=0
c_conf=0 ; c_drift=0 ; c_unman=0 ; c_exc=0 ; c_unk=0 ; c_blk=0
while IFS='|' read -r full name vis arch branch issues wiki projects dbom pushed; do
  [ -n "$full" ] || continue
  total=$((total+1))
  prot="Unknown"
  if [ "$arch" = "true" ]; then
    prot="NotChecked"
  elif gh api "repos/$full/branches/$branch/protection" > /dev/null 2>&1; then
    prot="Present"
  else
    # 403 (no access / plan limit) and 404 (no protection) are not
    # distinguishable without trusting error text — record Unknown.
    prot="Unknown"
  fi
  labels=$( { gh api --paginate "repos/$full/labels" --jq 'length' 2>/dev/null || true; } | awk '{s+=$1} END {print s+0}')
  # Mechanical classification, honest default: only seanchatmangpt/ggen and
  # the two acceptance sandboxes have any desired-state instances; everything
  # else is Unmanaged. The three managed-surface repos are Unknown here
  # because this read-only census runs no drift detection. Archived repos are
  # 保存-candidates, Blocked for write.
  cls="Unmanaged"
  if [ "$arch" = "true" ]; then
    cls="Blocked"
  elif [ "$full" = "seanchatmangpt/ggen" ] || [ "$full" = "seanchatmangpt/tcps-accept-test-sandbox" ] || [ "$full" = "seanchatmangpt/tcps-accept-test-2-sandbox" ]; then
    cls="Unknown"
  fi
  case "$cls" in
    Conforming) c_conf=$((c_conf+1)) ;;
    Drifted) c_drift=$((c_drift+1)) ;;
    Unmanaged) c_unman=$((c_unman+1)) ;;
    Exceptional) c_exc=$((c_exc+1)) ;;
    Unknown) c_unk=$((c_unk+1)) ;;
    Blocked) c_blk=$((c_blk+1)) ;;
  esac
  slug=$(echo "$full" | tr -c 'A-Za-z0-9' '-' | sed 's/-*$//')
  {
    echo "obs:repo-$slug a obs:RepoObservation ;"
    echo '    obs:fullName "'"$full"'" ;'
    echo '    obs:visibility "'"$vis"'" ;'
    echo '    obs:archived "'"$arch"'"^^xsd:boolean ;'
    echo '    obs:defaultBranch "'"$branch"'" ;'
    echo '    obs:protection "'"$prot"'" ;'
    echo '    obs:labelCount "'"$labels"'"^^xsd:integer ;'
    echo '    obs:hasIssues "'"$issues"'"^^xsd:boolean ;'
    echo '    obs:hasWiki "'"$wiki"'"^^xsd:boolean ;'
    echo '    obs:hasProjects "'"$projects"'"^^xsd:boolean ;'
    echo '    obs:deleteBranchOnMerge "'"$dbom"'"^^xsd:boolean ;'
    echo '    obs:pushedAt "'"$pushed"'" ;'
    echo '    obs:classification "'"$cls"'" .'
    echo
  } >> "$ttl_out"
  echo "| $full | $vis | $arch | $branch | $prot | $labels | $issues | $wiki | $projects | $dbom | $pushed | $cls |" >> "$md_out"
done < "$tmp/repos.txt"
{
  echo "obs:CensusSummary a obs:FleetCensus ;"
  echo '    obs:generatedAt "'"$now"'" ;'
  echo '    obs:repoCount "'"$total"'"^^xsd:integer ;'
  echo '    obs:conforming "'"$c_conf"'"^^xsd:integer ;'
  echo '    obs:drifted "'"$c_drift"'"^^xsd:integer ;'
  echo '    obs:unmanaged "'"$c_unman"'"^^xsd:integer ;'
  echo '    obs:exceptional "'"$c_exc"'"^^xsd:integer ;'
  echo '    obs:unknown "'"$c_unk"'"^^xsd:integer ;'
  echo '    obs:blocked "'"$c_blk"'"^^xsd:integer .'
} >> "$ttl_out"
{
  echo
  echo "## Classification counts"
  echo
  echo "| class | count |"
  echo "|-------|-------|"
  echo "| Conforming | $c_conf |"
  echo "| Drifted | $c_drift |"
  echo "| Unmanaged | $c_unman |"
  echo "| Exceptional | $c_exc |"
  echo "| Unknown | $c_unk |"
  echo "| Blocked | $c_blk |"
  echo "| total | $total |"
  echo
  echo "Honest default: every repo except seanchatmangpt/ggen and the two"
  echo "acceptance sandboxes is Unmanaged — no ghtf: desired-state instance"
  echo "exists for it. The three managed-surface repos are recorded Unknown"
  echo "because this read-only census runs no drift detection (that is"
  echo "drift-report.sh, a separate step). Archived repos are 保存-candidates"
  echo "and Blocked for any write. Conforming/Drifted are unreachable in"
  echo "Phase 1 by construction and correctly show 0."
  echo
  echo "## Hazard register"
  echo
  echo "1. Branch-protection reads can fail with 403 (token scope, non-admin,"
  echo "   or private-repo plan limits) or 404 (no protection); this census"
  echo "   records both as Unknown rather than guessing from error text."
  echo "2. gh api user/repos only lists repos affiliated with the current"
  echo "   token; org repos the token cannot see are absent from this census"
  echo "   entirely — absence here is not evidence of nonexistence."
  echo "3. Label counts on repos where the labels endpoint is forbidden read"
  echo "   as 0 — a permission gap indistinguishable from an empty label set"
  echo "   in this output."
  echo "4. Provider coverage limit: the pinned integrations/github provider"
  echo "   (v5.41.0) does not manage every observed field (e.g. wiki/projects"
  echo "   toggles are manageable; some plan-gated protection features are"
  echo "   not on private repos). Observation breadth exceeds management"
  echo "   breadth."
  echo "5. Archived repos are read-only at the API level: any future write"
  echo "   phase must treat them as Blocked until unarchived by a human."
  echo "6. Rate limits: a large fleet plus per-repo protection/label reads"
  echo "   can exhaust the API quota; rerun later if truncated by errors."
} >> "$md_out"
echo "fleet-census: total=$total conforming=$c_conf drifted=$c_drift unmanaged=$c_unman exceptional=$c_exc unknown=$c_unk blocked=$c_blk"
echo "fleet-census: ttl=$ttl_out md=$md_out"
