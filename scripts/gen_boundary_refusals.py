#!/usr/bin/env python3
"""Generate docs/BOUNDARY_REFUSALS.md from ontologies/shapes/boundary-refusal.shacl.ttl.

Lane A14 (v26.10.20). SPARQLs the typed boundary-refusal registry, emits a
per-surface table, and verifies enum<->TTL 1:1 parity against the canonical
enum inventory (generated refusals enums in ggen-engine / ggen-abb-sbb).

Usage:
  python3 scripts/gen_boundary_refusals.py            # (re)generate the doc
  python3 scripts/gen_boundary_refusals.py --check    # exit 1 on any drift
  python3 scripts/gen_boundary_refusals.py --emit-just-snippet
                                                      # print the justfile
                                                      # recipe (justfile is
                                                      # coordinator-owned)
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path
from typing import Any, Iterable, Sequence, cast

REPO = Path(__file__).resolve().parent.parent
TTL = REPO / "ontologies" / "shapes" / "boundary-refusal.shacl.ttl"
DOC = REPO / "docs" / "BOUNDARY_REFUSALS.md"

# Canonical enum inventory: the refusal codes the generated enums
# (crates/ggen-engine/src/generated/refusals.rs,
#  crates/ggen-abb-sbb/src/generated/refusals.rs) must carry. Enum identifiers
# use underscore form; dash-form registry codes normalize here.
CANONICAL_ENUMS = {
    "ENVELOPE_UNDECLARED",
    "REFUSED_STALE_LEASE",
    "VACUOUS_COURT",
    "CONTROL_REFUSED",
    "RESTORE_TAMPER",
    "WITNESS_STALE",
    "CENSUS_STALE",
    "FD_UNDECLARED_INPUT_DIALECT",
    "FD_DIALECT_FEATURE_DISALLOWED",
    "FD_MALFORMED_SYNTAX",
    "FD_REMOTE_CONTEXT_FORBIDDEN",
    "E_PARSE_N3",
    "E_PARSE_TURTLE",
    "E_PARSE_NTRIPLES",
}

SPARQL_SURFACES = """
    PREFIX br: <https://ggen.io/ontology/boundary-refusal#>
    PREFIX rdfs: <http://www.w3.org/2000/01/rdf-schema#>
    SELECT ?surface ?label ?prefix WHERE {
        ?s a br:Surface ; br:name ?surface ; rdfs:label ?label .
        OPTIONAL { ?s br:codePrefix ?prefix }
    } ORDER BY ?surface
"""

SPARQL_REFUSALS = """
    PREFIX br: <https://ggen.io/ontology/boundary-refusal#>
    PREFIX rdfs: <http://www.w3.org/2000/01/rdf-schema#>
    SELECT ?code ?surface ?inputClass ?fixture ?retryable ?owner ?fixHint WHERE {
        ?ind a br:BoundaryRefusal ;
             br:code ?code ;
             br:surface ?surface ;
             br:inputClass ?inputClass ;
             br:fixture ?fixture ;
             br:retryable ?retryable ;
             br:owner ?owner ;
             br:fixHint ?fixHint .
        OPTIONAL { ?ind rdfs:label ?label }
    } ORDER BY ?surface ?code
"""

SPARQL_PREFIX_VIOLATIONS = """
    PREFIX br: <https://ggen.io/ontology/boundary-refusal#>
    SELECT $this ?code ?surfaceName WHERE {
        $this br:code ?code ; br:surface ?surfaceName .
        FILTER NOT EXISTS {
            ?surface a br:Surface ; br:name ?surfaceName ; br:codePrefix ?prefix .
            FILTER(STRSTARTS(?code, ?prefix))
        }
    }
"""


def load_graph():
    from rdflib import Graph

    g = Graph()
    g.parse(TTL.as_posix(), format="turtle")
    return g


def normalize_code(code: str) -> str:
    # Dash-form envelope codes carry an "E-" transport prefix that the generated
    # enum identifier drops (E-ENVELOPE-UNDECLARED -> ENVELOPE_UNDECLARED).
    underscore = code.replace("-", "_")
    if underscore.startswith("E_ENVELOPE"):
        return underscore[len("E_") :]
    return underscore


def collect(g):
    surfaces: dict[str, list[str]] = {}
    for row in g.query(SPARQL_SURFACES):
        surfaces.setdefault(str(row.surface), [])
        p = row.prefix
        if p is not None and str(p) not in surfaces[str(row.surface)]:
            surfaces[str(row.surface)].append(str(p))

    refusals: list[dict] = []
    for row in g.query(SPARQL_REFUSALS):
        refusals.append(
            {
                "code": str(row.code),
                "surface": str(row.surface),
                "inputClass": str(row.inputClass),
                "fixtures": [],
                "retryable": str(row.retryable),
                "owner": str(row.owner),
                "fixHint": str(row.fixHint),
            }
        )
    # group fixtures per refusal (minCount 1, may be several)
    by_code: dict[str, dict] = {r["code"]: r for r in refusals}
    for row in g.query(
        """
        PREFIX br: <https://ggen.io/ontology/boundary-refusal#>
        SELECT ?code ?fixture WHERE {
            ?ind br:code ?code ; br:fixture ?fixture .
        } ORDER BY ?code ?fixture
        """
    ):
        by_code[str(row.code)]["fixtures"].append(str(row.fixture))
    return surfaces, refusals


def render(surfaces, refusals) -> str:
    lines = []
    lines.append("# Boundary Refusals")
    lines.append("")
    lines.append("<!-- GENERATED by scripts/gen_boundary_refusals.py from")
    lines.append("     ontologies/shapes/boundary-refusal.shacl.ttl — edit the TTL, not this file. -->")
    lines.append("")
    lines.append(
        "Typed boundary-refusal registry (v26.10.20, L13). Every code below is a"
    )
    lines.append(
        "typed refusal emitted on a boundary surface, witnessed by a fixture"
    )
    lines.append("court/test. Registry shape: `br:BoundaryCrossingShape` (closed).")
    lines.append("")
    for surface, prefixes in surfaces.items():
        lines.append(f"## Surface: `{surface}`")
        lines.append("")
        if prefixes:
            lines.append(
                "Declared code prefixes: " + ", ".join(f"`{p}`" for p in prefixes)
            )
            lines.append("")
        lines.append("| Code | Input class | Fixture | Retryable | Owner | Fix hint |")
        lines.append("|---|---|---|---|---|---|")
        for r in sorted(
            (r for r in refusals if r["surface"] == surface), key=lambda r: r["code"]
        ):
            fx = "<br>".join(f"`{f}`" for f in r["fixtures"])
            lines.append(
                f"| `{r['code']}` | `{r['inputClass'].split('#')[-1]}` | {fx} "
                f"| {r['retryable']} | {r['owner']} | {r['fixHint']} |"
            )
        lines.append("")
    lines.append(
        f"{len(refusals)} refusal codes across {len(surfaces)} surfaces."
    )
    lines.append("")
    return "\n".join(lines)


def verify(surfaces, refusals) -> list[str]:
    errors: list[str] = []
    ttl_enums = {normalize_code(r["code"]) for r in refusals}
    for missing in sorted(CANONICAL_ENUMS - ttl_enums):
        errors.append(f"enum present in CANONICAL_ENUMS but missing from TTL: {missing}")
    for extra in sorted(ttl_enums - CANONICAL_ENUMS):
        errors.append(f"code present in TTL but missing from CANONICAL_ENUMS: {extra}")
    if len(ttl_enums) != len(refusals):
        errors.append("duplicate refusal codes in TTL")
    known_surfaces = set(surfaces)
    for r in refusals:
        if r["surface"] not in known_surfaces:
            errors.append(f"{r['code']}: unknown surface {r['surface']!r}")
        if not r["fixtures"]:
            errors.append(f"{r['code']}: no fixture IRI")
    # prefix closure (mirror of the SHACL SPARQL constraint)
    for r in refusals:
        prefixes = surfaces.get(r["surface"], [])
        if prefixes and not any(r["code"].startswith(p) for p in prefixes):
            errors.append(
                f"{r['code']}: code prefix does not match any declared prefix of surface {r['surface']!r} ({prefixes})"
            )
    return errors


JUST_SNIPPET = """# Boundary-refusal doc parity (lane A14) — wire into an existing recipe or
# a coordinator-owned regen recipe; this lane does not edit justfile.
boundary-refusals:
    python3 scripts/gen_boundary_refusals.py

boundary-refusals-check:
    python3 scripts/gen_boundary_refusals.py --check
"""


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true", help="exit 1 on any drift")
    ap.add_argument(
        "--emit-just-snippet",
        action="store_true",
        help="print justfile recipe snippet (justfile is coordinator-owned)",
    )
    args = ap.parse_args()

    if args.emit_just_snippet:
        sys.stdout.write(JUST_SNIPPET)
        return 0

    g = load_graph()

    # SHACL prefix-closure constraint evaluated directly (shape + data in one
    # graph; pure-SPARQL check mirrors br:BoundaryCrossingShape's constraint).
    qresult = cast("Iterable[Sequence[Any]]", g.query(SPARQL_PREFIX_VIOLATIONS))
    violations = [
        (str(row[0]), str(row[1])) for row in qresult
    ]

    surfaces, refusals = collect(g)
    errors = verify(surfaces, refusals)
    for code, surface in violations:
        errors.append(f"{code}: SHACL prefix-closure violation on surface {surface!r}")

    content = render(surfaces, refusals)

    if args.check:
        if not DOC.exists():
            print(f"DRIFT: {DOC} missing", file=sys.stderr)
            return 1
        existing = DOC.read_text()
        if existing != content:
            print(f"DRIFT: {DOC} is stale — rerun without --check", file=sys.stderr)
            return 1
        if errors:
            for e in errors:
                print(f"DRIFT: {e}", file=sys.stderr)
            return 1
        print(f"OK: {DOC} in parity, {len(refusals)} codes, 0 drift")
        return 0

    DOC.write_text(content)
    if errors:
        for e in errors:
            print(f"ERROR: {e}", file=sys.stderr)
        return 1
    print(f"wrote {DOC} ({len(refusals)} codes, {len(surfaces)} surfaces)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
